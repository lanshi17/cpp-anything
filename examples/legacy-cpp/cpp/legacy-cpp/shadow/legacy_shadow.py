def encode(value):
    """The wire tags the recorder and the C++ codec share."""
    if value is None or isinstance(value, bool):
        return value
    if isinstance(value, int):
        return value if -(2**63) <= value < 2**63 else {"$int": str(value)}
    if isinstance(value, float):
        return value
    if isinstance(value, str):
        return value
    if isinstance(value, (list, tuple)):
        items = [encode(item) for item in value]
        return items if isinstance(value, list) else {"$tuple": items}
    if isinstance(value, (set, frozenset)):
        items = [encode(item) for item in value]
        return {"$set": sorted(items, key=lambda item: json.dumps(item, sort_keys=True))}
    if isinstance(value, dict):
        if all(isinstance(key, str) for key in value):
            return {key: encode(item) for key, item in value.items()}
        return {"$map": [[encode(key), encode(item)] for key, item in value.items()]}
    if isinstance(value, (bytes, bytearray)):
        import base64
        return {"$bytes": base64.b64encode(bytes(value)).decode("ascii")}
    return {"$opaque": repr(value)}


def _kind(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "string"
    if isinstance(value, list):
        return "list"
    if isinstance(value, dict):
        return "object"
    return "other"


def compare(expected, got):
    """None when equal, else the reason. Mirrors `cpp-anything diff`."""
    expected_err = expected.get("err") if isinstance(expected, dict) else None
    got_err = got.get("err") if isinstance(got, dict) else None
    if expected_err is not None or got_err is not None:
        if expected_err is None:
            return "the original returns a value, the port raises %s" % (got_err or {}).get("type")
        if got_err is None:
            return "the original raises %s, the port returns a value" % expected_err.get("type")
        if expected_err.get("type") != got_err.get("type"):
            return "error type: expected %s, got %s" % (expected_err.get("type"), got_err.get("type"))
        return None
    left = expected.get("ok", expected)
    right = got.get("ok", got)
    return _compare_value(left, right)


def _compare_value(left, right):
    if isinstance(left, dict) and isinstance(right, dict) and set(left) == set(right):
        if set(left) <= {"$tuple", "$set"}:
            left, right = list(left.values())[0], list(right.values())[0]
        elif "$map" in left:
            left, right = left["$map"], right["$map"]
        elif any(key.startswith("$") for key in left):
            return None if encode(left) == encode(right) else "value differs: %r vs %r" % (left, right)
        else:
            for key in left:
                reason = _compare_value(left[key], right.get(key))
                if reason:
                    return "key %r: %s" % (key, reason)
            return None
    if isinstance(left, list) and isinstance(right, list):
        if len(left) != len(right):
            return "length: expected %d items, got %d" % (len(left), len(right))
        for index, (a, b) in enumerate(zip(left, right)):
            reason = _compare_value(a, b)
            if reason:
                return "item %d: %s" % (index, reason)
        return None
    if isinstance(left, float) or isinstance(right, float):
        if not isinstance(left, (int, float)) or not isinstance(right, (int, float)):
            return "type: expected %s, got %s" % (_kind(left), _kind(right))
        a, b = float(left), float(right)
        if math.isnan(a) or math.isnan(b):
            return None if (math.isnan(a) and math.isnan(b)) else "NaN mismatch"
        if TOLERANCE > 0:
            return None if abs(a - b) <= TOLERANCE * max(1.0, abs(a), abs(b)) else "float: %r vs %r" % (a, b)
        if a != b:
            return "float: %r vs %r" % (a, b)
        if math.copysign(1.0, a) != math.copysign(1.0, b):
            return "-0.0 vs 0.0"
        return None
    if _kind(left) != _kind(right):
        return "type: expected a %s, got a %s" % (_kind(left), _kind(right))
    return None if left == right else "value: %r vs %r" % (left, right)


def _shadow_call(name, args):
    try:
        payload = json.dumps([encode(item) for item in args], ensure_ascii=False)
    except (TypeError, ValueError) as error:
        return {"err": {"type": "EncodingError", "msg": str(error)}}
    pointer = _library.cppan_shadow_call(name.encode("utf-8"), payload.encode("utf-8"))
    if not pointer:
        return {"err": {"type": "ShadowError", "msg": "the port returned nothing"}}
    try:
        return json.loads(ctypes.string_at(pointer).decode("utf-8"))
    finally:
        _library.cppan_shadow_free(pointer)


def _log(entry):
    try:
        os.makedirs(os.path.dirname(LOG), exist_ok=True)
        with open(LOG, "a", encoding="utf-8") as handle:
            handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except OSError:
        pass


def _observe(name, original, args, kwargs, expected):
    if os.environ.get("CPPAN_SHADOW") == "off":
        return
    got = _shadow_call(name, args)
    reason = compare(expected, got)
    if reason is None:
        return
    _log({
        "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "fn": name,
        "args": [encode(item) for item in args],
        "expected": expected,
        "got": got,
        "reason": reason,
        "kwargs": sorted(kwargs),
    })


def _wrap(name):
    original = getattr(_original, name)

    def shadowed(*args, **kwargs):
        try:
            result = original(*args, **kwargs)
        except BaseException as error:
            expected = {"err": {"type": type(error).__name__, "msg": str(error)}}
            _observe(name, original, args, kwargs, expected)
            raise
        _observe(name, original, args, kwargs, {"ok": encode(result)})
        return result

    shadowed.__name__ = getattr(original, "__name__", name)
    shadowed.__doc__ = getattr(original, "__doc__", None)
    return shadowed


for _name in FUNCTIONS:
    if hasattr(_original, _name):
        globals()[_name] = _wrap(_name)
