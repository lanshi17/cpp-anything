inline std::string decode(std::string text) {
  std::string out;
  out.reserve(text.size());
  for (std::size_t index = 0; index < text.size(); ++index) {
    if (text[index] == '%' && index + 2 < text.size()) {
      const auto hex = [](char ch) -> int {
        if (ch >= '0' && ch <= '9') return ch - '0';
        if (ch >= 'a' && ch <= 'f') return ch - 'a' + 10;
        if (ch >= 'A' && ch <= 'F') return ch - 'A' + 10;
        return -1;
      };
      const int high = hex(text[index + 1]);
      const int low = hex(text[index + 2]);
      if (high >= 0 && low >= 0) {
        out.push_back(static_cast<char>(high * 16 + low));
        index += 2;
        continue;
      }
    }
    out.push_back(text[index] == '+' ? ' ' : text[index]);
  }
  return out;
}

inline Request parse_request(const std::string& raw) {
  Request request;
  const std::size_t line_end = raw.find("\r\n");
  const std::string_view line(raw.data(), line_end == std::string::npos ? raw.size() : line_end);
  const std::size_t first = line.find(' ');
  if (first != std::string_view::npos) {
    request.method = std::string(line.substr(0, first));
    const std::size_t second = line.find(' ', first + 1);
    const std::string_view target = second == std::string_view::npos
                                        ? line.substr(first + 1)
                                        : line.substr(first + 1, second - first - 1);
    const std::size_t question = target.find('?');
    request.path = decode(std::string(target.substr(0, question)));
    if (question != std::string_view::npos) {
      request.query = std::string(target.substr(question + 1));
    }
  }
  const std::size_t body_at = raw.find("\r\n\r\n");
  if (body_at != std::string::npos) request.body = raw.substr(body_at + 4);
  return request;
}

inline std::string render_response(const Response& response) {
  std::string out = "HTTP/1.1 " + std::to_string(response.status) + " OK\r\n";
  out += "content-type: " + response.content_type + "\r\n";
  out += "content-length: " + std::to_string(response.body.size()) + "\r\n";
  out += "connection: close\r\n\r\n";
  out += response.body;
  return out;
}

