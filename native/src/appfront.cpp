Result<std::size_t> write(const std::filesystem::path& app_dir,
                          const appcase::Config& config) {
  // The front door includes each unit's header; a module unit has none.
  const std::filesystem::path cpp_dir = app_dir.parent_path();
  if (cpp_dir.empty()) {
    return std::unexpected(path_text(app_dir) + ": no parent directory");
  }
  std::error_code error;
  std::filesystem::directory_iterator iterator(cpp_dir, error);
  if (!error) {
    for (const auto& entry : iterator) {
      const auto project = Project::load(entry.path());
      if (project.has_value() && project->modules) {
        return std::unexpected(
            path_text(entry.path()) +
            " is a C++20 module unit, and the app front door includes unit headers: regenerate "
            "it with `cpp-anything bridge <repo> <unit> --modules off`");
      }
    }
  }
  std::size_t written = 0;
  std::string cmake = sub(std::string(kCmake), "{{LIFTED}}",
                          config.lifted ? "add_compile_definitions(CPPAN_LIFTED)" : "");
  if (auto result = write_file(app_dir / "CMakeLists.txt", cmake); !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  auto routes = load_routes(app_dir);
  if (!routes.has_value()) return std::unexpected(routes.error());
  const std::filesystem::path repo =
      app_dir.parent_path().parent_path().empty() ? std::filesystem::path(".")
                                                  : app_dir.parent_path().parent_path();
  const std::string main_text =
      config.http ? render_proxy_main(config, repo) : std::string(kMainCpp);
  if (auto result = write_file(app_dir / "src" / "main.cpp", main_text); !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  if (auto result = write_file(app_dir / "src" / "fallback.cpp", render_fallback(config, repo));
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  if (auto result = write_file(app_dir / "include" / "cppan" / "glue.hpp", kGlueHpp);
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  if (auto result = write_file(app_dir / "src" / "routing.cpp", render_routing(*routes));
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  if (config.http) {
    // Servers route natively first and proxy what no unit answers. Lifted builds
    // drop the original entirely and answer 404 for unwired paths.
    if (auto result = write_file(app_dir / "src" / "fallback.cpp", ""); !result.has_value()) {
      return std::unexpected(result.error());
    }
    if (auto result = write_file(app_dir / "src" / "routing.cpp", render_http_routing(*routes));
        !result.has_value()) {
      return std::unexpected(result.error());
    }
    if (auto result = write_file(app_dir / "include" / "cppan" / "http.hpp", kHttpHpp);
        !result.has_value()) {
      return std::unexpected(result.error());
    }
    ++written;
    for (const Route& route : *routes) {
      if (!route.path.has_value()) continue;
      const std::filesystem::path handler = app_dir / "src" / ("http_" + route.unit + ".cpp");
      if (std::filesystem::exists(handler, error)) continue;
      std::string text = sub(std::string(kHttpGlueCpp), "{{UNIT}}", route.unit);
      text = sub(std::move(text), "{{NS}}", route.unit);
      text = sub(std::move(text), "{{HANDLER}}", "cppan_http_" + route.unit);
      if (auto result = write_file(handler, text); !result.has_value()) {
        return std::unexpected(result.error());
      }
    }
  }
  if (auto result = write_file(app_dir / "README.md", render_readme(config, *routes));
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  return written;
}

std::size_t route_count(const std::filesystem::path& app_dir) {
  auto routes = load_routes(app_dir);
  return routes.has_value() ? routes->size() : 0;
}

Result<std::filesystem::path> wire_http(const std::filesystem::path& app_dir,
                                        const std::filesystem::path& repo,
                                        const std::string& unit,
                                        const std::vector<std::string>& texts,
                                        std::optional<std::filesystem::path> project) {
  std::string normalized = sanitize_identifier(unit);
  std::filesystem::path project_dir;
  if (project.has_value()) {
    std::error_code error;
    project_dir = std::filesystem::canonical(*project, error);
    if (error) {
      return std::unexpected(path_text(*project) + ": " + io_error(error.value()));
    }
  } else {
    std::string dashed = normalized;
    std::replace(dashed.begin(), dashed.end(), '_', '-');
    const std::filesystem::path guess = repo / "cpp" / dashed;
    std::error_code error;
    if (!std::filesystem::exists(guess / "CMakeLists.txt", error)) {
      return std::unexpected("cannot find the unit's project: looked for " + path_text(guess) +
                             ". Pass `--project <dir>` (the folder `bridge` wrote for " + unit +
                             ")");
    }
    project_dir = canonical_or_self(guess);
  }
  auto loaded = Project::load(project_dir);
  if (!loaded.has_value()) return std::unexpected(loaded.error());
  if (loaded->modules) {
    return std::unexpected(
        path_text(project_dir) +
        " is a C++20 module unit, and the HTTP front door includes unit headers: regenerate it "
        "with `cpp-anything bridge <repo> <unit> --modules off`");
  }
  const std::string ns = codegen::namespace_of(*loaded);
  auto routes = load_routes(app_dir);
  if (!routes.has_value()) return std::unexpected(routes.error());
  for (const std::string& text : texts) {
    auto parsed = parse_http_route(text);
    if (!parsed.has_value()) return std::unexpected(parsed.error());
    const auto& [method, path] = *parsed;
    for (const Route& existing : *routes) {
      if (existing.unit == normalized) continue;
      const bool same_path = existing.path.has_value() && *existing.path == path;
      const bool same_method =
          existing.method == method || !existing.method.has_value() || !method.has_value();
      if (same_path && same_method) {
        return std::unexpected(existing.unit + " already answers " + path + " (" +
                               (existing.method.has_value() ? *existing.method
                                                            : std::string("any method")) +
                               ")");
      }
    }
    routes->erase(std::remove_if(routes->begin(), routes->end(),
                                 [&](const Route& route) {
                                   return route.unit == normalized &&
                                          route.path.has_value() && *route.path == path &&
                                          route.method == method;
                                 }),
                  routes->end());
    routes->push_back(Route{std::string(), method, path, normalized, path_text(project_dir)});
  }
  if (auto saved = save_routes(app_dir, *routes); !saved.has_value()) {
    return std::unexpected(saved.error());
  }
  const std::filesystem::path handler = app_dir / "src" / ("http_" + normalized + ".cpp");
  std::error_code error;
  if (!std::filesystem::exists(handler, error)) {
    std::string text = sub(std::string(kHttpGlueCpp), "{{UNIT}}", normalized);
    text = sub(std::move(text), "{{NS}}", ns);
    text = sub(std::move(text), "{{HANDLER}}", "cppan_http_" + normalized);
    if (auto result = write_file(handler, text); !result.has_value()) {
      return std::unexpected(result.error());
    }
  }
  auto config = appcase::Config::load(repo / appcase::kCasesDir);
  if (!config.has_value()) return std::unexpected(config.error());
  if (auto written = write(app_dir, *config); !written.has_value()) {
    return std::unexpected(written.error());
  }
  return handler;
}

Result<std::filesystem::path> wire(const std::filesystem::path& app_dir,
                                   const std::filesystem::path& repo, const std::string& unit,
                                   const std::string& command,
                                   std::optional<std::filesystem::path> project) {
  const std::string normalized = sanitize_identifier(unit);
  std::filesystem::path project_dir;
  if (project.has_value()) {
    std::error_code error;
    project_dir = std::filesystem::canonical(*project, error);
    if (error) return std::unexpected(path_text(*project) + ": " + io_error(error.value()));
  } else {
    std::string dashed = normalized;
    std::replace(dashed.begin(), dashed.end(), '_', '-');
    const std::filesystem::path guess = repo / "cpp" / dashed;
    std::error_code error;
    if (!std::filesystem::exists(guess / "CMakeLists.txt", error)) {
      return std::unexpected("cannot find the unit's project: looked for " + path_text(guess) +
                             ". Pass `--project <dir>` (the                      folder `bridge` "
                             "wrote for " +
                             unit + ")");
    }
    project_dir = canonical_or_self(guess);
  }
  std::error_code error;
  if (!std::filesystem::exists(project_dir / "src" / "port.cpp", error)) {
    return std::unexpected(path_text(project_dir) +
                           " is not a cpp-anything project (no src/port.cpp)");
  }
  auto routes = load_routes(app_dir);
  if (!routes.has_value()) return std::unexpected(routes.error());
  routes->erase(std::remove_if(routes->begin(), routes->end(),
                               [&](const Route& route) { return route.command == command; }),
                routes->end());
  routes->push_back(
      Route{command, std::nullopt, std::nullopt, normalized, path_text(project_dir)});
  if (auto saved = save_routes(app_dir, *routes); !saved.has_value()) {
    return std::unexpected(saved.error());
  }
  const std::filesystem::path glue = app_dir / "src" / ("glue_" + normalized + ".cpp");
  if (!std::filesystem::exists(glue, error)) {
    std::string text = sub(std::string(kGlueCpp), "CPPAN_HANDLER", "handle_" + normalized);
    text = sub(std::move(text), "{{NS}}", normalized);
    text = sub(std::move(text), "{{COMMAND}}", command);
    if (auto result = write_file(glue, text); !result.has_value()) {
      return std::unexpected(result.error());
    }
  }
  auto config = appcase::Config::load(repo / appcase::kCasesDir);
  if (!config.has_value()) return std::unexpected(config.error());
  if (auto written = write(app_dir, *config); !written.has_value()) {
    return std::unexpected(written.error());
  }
  return glue;
}

Result<std::size_t> write_library(const std::filesystem::path& repo,
                                  const std::filesystem::path& app_dir) {
  const std::filesystem::path cpp_dir = repo / "cpp";
  std::error_code error;
  std::filesystem::directory_iterator iterator(cpp_dir, error);
  if (error) return std::unexpected(path_text(cpp_dir) + ": " + io_error(error.value()));
  std::vector<std::pair<Project, std::string>> units;
  for (const auto& entry : iterator) {
    const std::filesystem::path path = entry.path();
    std::error_code kind_error;
    if (!std::filesystem::is_directory(path, kind_error) || path == app_dir) continue;
    auto project = Project::load(path);
    if (!project.has_value()) continue;
    if (project->modules) {
      return std::unexpected(
          path_text(path) +
          " is a C++20 module unit, and the library front door includes unit headers: regenerate "
          "it with `cpp-anything bridge <repo> <unit> --modules off`");
    }
    if (!std::filesystem::exists(path / "CMakeLists.txt", kind_error)) continue;
    units.emplace_back(*project, codegen::namespace_of(*project));
  }
  if (units.empty()) {
    return std::unexpected("no bridged units under " + path_text(cpp_dir) +
                           ": run `cpp-anything bridge` for the units the library re-exports, "
                           "then `app wire <unit>` or `app front-door --library`");
  }
  std::stable_sort(units.begin(), units.end(),
                   [](const auto& left, const auto& right) { return left.second < right.second; });
  std::string cmake =
      "# Generated by cpp-anything app front-door --library: the ports this library "
      "re-exports.\n";
  for (const auto& [project, _] : units) {
    const std::string target = "cppan_port_" + sanitize_identifier(project.unit);
    cmake += "add_subdirectory(" + path_text(project.dir) + " unit_" + target +
             " EXCLUDE_FROM_ALL)\n";
    cmake += "list(APPEND CPPAN_UNIT_LIBS " + target + ")\n";
  }
  std::size_t written = 0;
  if (auto result = write_file(app_dir / "units.cmake", cmake); !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  const std::string target = sanitize_identifier(app_name(repo));
  if (auto result = write_file(app_dir / "CMakeLists.txt",
                               sub(std::string(kLibraryCmake), "{{TARGET}}", target));
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  std::string header =
      "// Generated by cpp-anything app front-door --library.\n"
      "//\n"
      "// Each unit's port is re-exported under `cppan_api`; link the `cppan_api`\n"
      "// target and include this header. C++20/23, warnings on.\n"
      "#pragma once\n\n"
      "#include <cppan/wire.hpp>\n";
  for (const auto& [_, ns] : units) header += "#include <" + ns + "/port.hpp>\n";
  header +=
      "\nextern \"C\" const char* cppan_api_units();\n\n"
      "namespace cppan_api {\n\n"
      "/// The units this library re-exports, comma separated.\n"
      "inline const char* units() { return cppan_api_units(); }\n";
  for (const auto& [project, ns] : units) {
    header += "namespace " + ns + " = ::" + ns + ";  // " + project.module + "\n";
  }
  header += "\n}  // namespace cppan_api\n";
  if (auto result = write_file(app_dir / "include" / "cppan" / "api.hpp", header);
      !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  std::string names;
  for (std::size_t index = 0; index < units.size(); ++index) {
    if (index > 0) names += ",";
    names += units[index].second;
  }
  std::string api =
      "// Generated by cpp-anything app front-door --library.\n"
      "#include \"cppan/api.hpp\"\n\n"
      "extern \"C\" {\n\n"
      "const char* cppan_api_units() { return \"" +
      names +
      "\"; }\n\n"
      "}  // extern \"C\"\n";
  if (auto result = write_file(app_dir / "src" / "api.cpp", api); !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  std::string unit_lines;
  for (std::size_t index = 0; index < units.size(); ++index) {
    if (index > 0) unit_lines += "\n";
    unit_lines += "- `cppan_api::" + units[index].second + "` \xE2\x80\x94 " +
                  units[index].first.module;
  }
  std::string readme = "# " + target +
                       " \xE2\x80\x94 C++ library front door\n\n"
                       "Generated by `cpp-anything app front-door --library`: every bridged "
                       "unit's\n"
                       "port is re-exported under `cppan_api`, with no entry point and no "
                       "fallback.\n\n"
                       "## Units\n\n" +
                       unit_lines +
                       "\n\n## Use\n\n"
                       "```cpp\n"
                       "#include <cppan/api.hpp>\n\n"
                       "int main() {\n"
                       "  // auto words = cppan_api::UNIT::word_count(std::string_view{\"a b c\"});\n"
                       "}\n"
                       "```\n\n"
                       "```sh\n"
                       "cmake -S . -B build && cmake --build build -j\n"
                       "```\n\n"
                       "Consumers link the `cppan_api` target (or the static library and each "
                       "unit's\n"
                       "`cppan_port_*` target listed in `units.cmake`).\n";
  if (auto result = write_file(app_dir / "README.md", readme); !result.has_value()) {
    return std::unexpected(result.error());
  }
  ++written;
  return written;
}

Result<std::filesystem::path> build_library(const std::filesystem::path& app_dir) {
  auto build_dir = build_tree(app_dir);
  if (!build_dir.has_value()) return std::unexpected(build_dir.error());
#if defined(_WIN32)
  const std::filesystem::path library = *build_dir / "cppan_api.lib";
#else
  const std::filesystem::path library = *build_dir / "libcppan_api.a";
#endif
  std::error_code error;
  if (!std::filesystem::exists(library, error)) {
    return std::unexpected("build succeeded but " + path_text(library) + " is missing");
  }
  return library;
}

Result<std::filesystem::path> build(const std::filesystem::path& app_dir) {
  auto build_dir = build_tree(app_dir);
  if (!build_dir.has_value()) return std::unexpected(build_dir.error());
#if defined(_WIN32)
  const std::filesystem::path exe = *build_dir / "cppan_app.exe";
#else
  const std::filesystem::path exe = *build_dir / "cppan_app";
#endif
  std::error_code error;
  if (!std::filesystem::exists(exe, error)) {
    return std::unexpected("build succeeded but " + path_text(exe) + " is missing");
  }
  return exe;
}

