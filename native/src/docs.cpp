using Rows = std::vector<std::vector<std::string>>;

std::string table(const std::vector<std::string>& headers, const Rows& rows) {
  std::string out = "| ";
  for (std::size_t index = 0; index < headers.size(); ++index) {
    if (index > 0) out += " | ";
    out += headers[index];
  }
  out += " |\n|";
  for (std::size_t index = 0; index < headers.size(); ++index) out += " --- |";
  out += '\n';
  for (const auto& row : rows) {
    out += "| ";
    for (std::size_t index = 0; index < row.size(); ++index) {
      if (index > 0) out += " | ";
      out += row[index];
    }
    out += " |\n";
  }
  return out;
}

std::string escape(std::string text) {
  std::string out;
  out.reserve(text.size());
  for (const char ch : text) {
    if (ch == '|') {
      out += "\\|";
    } else if (ch == '<') {
      out += "&lt;";
    } else if (ch == '>') {
      out += "&gt;";
    } else {
      out += ch;
    }
  }
  return out;
}

std::string cell(const Support* support) {
  if (support == nullptr) return "—";
  switch (support->status) {
    case Status::Yes: return support->min.value_or("yes");
    case Status::Partial: return support->min.value_or("?") + " (partial)";
    case Status::No: return "—";
  }
  return "—";
}

std::string header(const Matrix& matrix, std::string_view title, std::string_view blurb) {
  std::string out =
      "<!-- generated by `cpp-anything matrix docs` from data/matrix.json — do not edit -->\n";
  out += "# ";
  out += title;
  out += "\n\n";
  out += blurb;
  out += "\n\nMatrix: ";
  out += std::to_string(matrix.features.size());
  out += " features, generated ";
  out += matrix.generated_at;
  out += ", from cppreference (";
  out += matrix.license;
  out += ").\n";
  out += "Refresh the data with `cpp-anything matrix sync` (or `scripts/sync_matrix.py`), then \n";
  out += "re-render with `cpp-anything matrix docs`.\n\n";
  return out;
}

bool has_standard(const Matrix& matrix, std::string_view standard) {
  return std::ranges::any_of(matrix.features,
                             [&](const Feature& feature) { return feature.standard == standard; });
}

std::optional<std::string> latest_known(const Matrix& matrix, std::string_view toolchain) {
  // C++26 draft papers can name a release that has not shipped; the guides are
  // about C++20/23 ports, so those releases are not used as "newest".
  std::optional<std::string> best;
  for (const Feature& feature : matrix.features) {
    if (feature.std_number() > 23) continue;
    const auto release = feature.first_release(toolchain);
    if (!release.has_value()) continue;
    if (!best.has_value() || version_cmp(*release, *best) >= 0) best = release;
  }
  return best;
}

std::vector<std::string> counts_row(const Matrix& matrix, std::string_view toolchain,
                                    std::string_view version, std::string_view standard) {
  const auto [supported, partial, missing] = matrix.supported_counts(toolchain, version, standard);
  return {std::string(standard), std::to_string(supported), std::to_string(partial),
          std::to_string(missing)};
}

constexpr std::string_view kGccNotes = R"(## Flags and defaults

- `-std=c++20` and, since GCC 13, `-std=c++23`. GCC 11 and 12 know the same mode as `-std=c++2b`; GCC 15 adds `-std=c++26`.
- `-std=c++23` does not turn on experimental library features: libstdc++ gates some of them behind `-D_GLIBCXX_USE_CXX11_ABI=1` (default) and, historically, `-fno-exceptions` changes what `<stacktrace>` can do.
- `<stacktrace>` needs an extra library: `-lstdc++exp` (GCC 14 and later) or `-lstdc++_libbacktrace` (GCC 12/13 built with `--enable-libstdcxx-backtrace`). The matrix row for `std::stacktrace` carries the same note.
- Modules are incomplete: `-fmodules-ts`, and `import std;` needs a BMI that a project builds itself. Treat modules as unavailable unless you plan to build them.

## Where GCC is behind

GCC's core language support leads its library: C++23 core features land in 11–15, while libstdc++ still has holes in C++23 facilities (freestanding additions, `<mdspan>` details, C++26 papers arriving as DRs).

Vendor pages: [core status](https://gcc.gnu.org/projects/cxx-status.html), [libstdc++ status](https://gcc.gnu.org/onlinedocs/libstdc++/manual/status.html).
)";

constexpr std::string_view kClangNotes = R"(## Flags and defaults

- `-std=c++20` everywhere; `-std=c++23` on Clang 17 and later (16 and older spell it `-std=c++2b`); `-std=c++26` on Clang 21 and later.
- Clang is a compiler, libc++ is a library, and they version together but ship separately. The **clang** column of cppreference's library tables is libc++ — that is what this guide reports. If you build with Clang and an older libstdc++, the library half of every table moves to the GCC row for that libstdc++ release (`g++ -print-file-name=libstdc++.so` tells you what you have).
- `-stdlib=libc++` selects libc++. On macOS, Apple Clang ships libc++ (tracked as **apple-clang** in the matrix).
- Modules: `-fmodules` plus explicit BMI files; `import std;` is complete only in recent releases (`CPPAN_HAS_LIB_MODULES` in the generated profile).

## Where Clang is behind

Core language support and libc++ do not move together: `std::print`, `std::flat_map` and parts of `<format>` reached libc++ later than libstdc++, and `std::stacktrace` was still incomplete at the time of the last sync. The per-standard guides list every gap with the release that closes it.

Vendor pages: [Clang core status](https://clang.llvm.org/cxx_status.html), [libc++ status](https://libcxx.llvm.org/).
)";

constexpr std::string_view kMsvcNotes = R"(## Flags and defaults

- `/std:c++20`, `/std:c++latest`. `/std:c++23preview` exists on recent VS 2022 releases; the stable spelling for C++23 work is `/std:c++latest`.
- `/Zc:__cplusplus` makes `__cplusplus` report the selected standard. Without it MSVC reports `199711L`, no matter what you pass, and every `#if __cplusplus` check lies. `_MSVC_LANG` always tells the truth. cpp-anything's generated `CMakeLists.txt` passes `/Zc:__cplusplus`.
- `/permissive-` is on in the template: two-phase lookup, stricter conversions.
- MSVC versions are reported as compiler versions (`19.xx`). The matrix stores the mapping to Visual Studio releases; the table below shows both.
- `<format>`/`<print>` arrive as MSVC STL features, so a compiler update alone is not enough — the STL ships with the toolset.

## Where MSVC is behind

C++23 core is nearly complete in recent toolsets; the library column lags on freestanding additions and a few papers recorded per release. MSVC is the toolchain that needs `/Zc:__cplusplus` and a recent STL for C++20/23 facilities, which is why the generated profile refuses to guess and asks the matrix.

Vendor pages: [language conformance](https://learn.microsoft.com/en-us/cpp/overview/visual-cpp-language-conformance), [STL changelog](https://github.com/microsoft/STL/wiki/Changelog).
)";

std::string index_doc(const Matrix& matrix) {
  std::string out = header(
      matrix, "C++ toolchain guides",
      "What every compiler release supports, standard by standard, and what cpp-anything's "
      "generated code may therefore use. The data is cppreference's compiler-support tables; the "
      "recommendation is computed from it, not written by hand.");
  out += "## Read this first\n\n";
  out += table({"if you want to", "read"},
               {
                   {"pick a compiler and standard for a port",
                    "[selecting-a-toolchain.md](selecting-a-toolchain.md)"},
                   {"know what your GCC does", "[compilers/gcc.md](compilers/gcc.md)"},
                   {"know what your Clang + libc++ does",
                    "[compilers/clang.md](compilers/clang.md), [compilers/llvm.md](compilers/llvm.md)"},
                   {"know what your MSVC does", "[compilers/msvc.md](compilers/msvc.md)"},
                   {"look up one standard", "[standards/](standards/)"},
                   {"look up one feature", "`cpp-anything matrix explain std::expected`"},
               });
  out += "\n## First release with complete support\n\n";
  out +=
      "Computed as the highest first-release among that standard's features: a release appears "
      "here only when it has every core feature (or every library feature) the matrix records. "
      "Features cppreference still marks partial do not block this number — each compiler's guide "
      "lists them, and `partial` is what `matrix features` reports.\n\n";
  Rows rows;
  for (const std::string_view standard : {"c++17", "c++20", "c++23"}) {
    if (!has_standard(matrix, standard)) continue;
    const auto core = [&](std::string_view toolchain) {
      return matrix.first_complete_core(toolchain, standard).value_or("—");
    };
    const auto library = [&](std::string_view toolchain) {
      return matrix.first_complete_library(toolchain, standard).value_or("—");
    };
    rows.push_back({std::string(standard), core("gcc"), library("gcc"), core("clang"),
                    library("clang"), core("msvc"), library("msvc")});
  }
  out += table({"standard", "GCC core", "libstdc++", "Clang core", "libc++", "MSVC core",
                "MSVC STL"},
               rows);
  out +=
      "\n`—` means no release in the matrix implements all of it yet (or cppreference records no "
      "complete release). Partial support is common in both columns; see each compiler's guide for "
      "the gaps.\n";
  out += "\n## Provenance\n\n";
  Rows provenance;
  for (const Source& source : matrix.sources) {
    std::string title = source.title;
    if (const std::size_t at = title.find("Template:"); at != std::string::npos) {
      title.erase(at, std::string("Template:").size());
    }
    provenance.push_back({"`" + escape(title) + "`", source.revision.value_or("—"),
                          source.timestamp.value_or("—"), "[raw](" + source.url + ")"});
  }
  out += table({"page", "revision", "fetched", "source"}, provenance);
  out += "\n## How cpp-anything uses the matrix\n\n";
  out +=
      "- `bridge` writes `include/cppan/profile.hpp` for the chosen toolchain: one `CPPAN_HAS_*` "
      "macro per facility, computed from the matrix, plus a `static_assert` on the standard.\n";
  out +=
      "- Generated code uses `std::expected` (C++23). If the target cannot provide it, `gate` "
      "fails at the matrix step with the release you need, before a compiler error.\n";
  out +=
      "- `cpp-anything matrix features --toolchain X --version Y --std Z` answers \"can this "
      "toolchain build the port\" without compiling anything.\n";
  return out;
}

std::string compiler_doc(const Matrix& matrix, std::string_view id, std::string_view title) {
  const std::string label = matrix.toolchain_label(id);
  std::string out = header(
      matrix, label,
      std::format("What each {} release supports, and what cpp-anything's generated code assumes "
                  "about it. Numbers are releases, not dates; a `(partial)` cell means the release "
                  "implements part of the feature.",
                  title));
  const std::string latest = latest_known(matrix, id).value_or("?");
  out += std::format("## At {} {} (the newest release the matrix records for C++20/23)\n\n", label,
                     latest);
  Rows counts;
  for (const std::string_view standard : {"c++17", "c++20", "c++23"}) {
    if (!has_standard(matrix, standard)) continue;
    counts.push_back(counts_row(matrix, id, latest, standard));
  }
  out += table({"standard", "supported", "partial", "not yet"}, counts);
  out += "\n## First release with complete support\n\n";
  Rows completeness;
  for (const std::string_view standard : {"c++11", "c++14", "c++17", "c++20", "c++23"}) {
    if (!has_standard(matrix, standard)) continue;
    completeness.push_back({std::string(standard),
                            matrix.first_complete_core(id, standard).value_or("—"),
                            matrix.first_complete_library(id, standard).value_or("—")});
  }
  out += table({"standard", "core language", "library"}, completeness);

  out += std::format("\n## What {} {} still misses in C++23\n\n", label, latest);
  const Audit audit = matrix.audit(id, latest, "c++23");
  if (audit.missing.empty() && audit.partial.empty()) {
    out += "Nothing recorded: every C++23 feature in the matrix is implemented.\n";
  } else {
    Rows rows;
    std::size_t shown = 0;
    for (const Feature* feature : audit.missing) {
      if (shown++ >= 25) break;
      rows.push_back({escape(feature->name), std::string(kind_label(feature->kind)),
                      feature->macro_id});
    }
    shown = 0;
    for (const Feature* feature : audit.partial) {
      if (shown++ >= 25) break;
      rows.push_back({escape(feature->name) + " (partial)",
                      std::string(kind_label(feature->kind)), feature->macro_id});
    }
    out += table({"feature", "kind", "macro"}, rows);
    out += std::format("\n{} of {} C++23 features are missing or partial in this release.\n",
                       audit.missing.size() + audit.partial.size(),
                       audit.missing.size() + audit.partial.size() + audit.supported.size());
  }

  out += "\n## Features by release\n\n";
  std::vector<std::pair<std::string, std::vector<const Feature*>>> by_release;
  for (const Feature& feature : matrix.features) {
    const auto release = feature.first_release(id);
    if (!release.has_value()) continue;
    auto found = std::find_if(by_release.begin(), by_release.end(),
                              [&](const auto& group) { return group.first == *release; });
    if (found == by_release.end()) {
      by_release.push_back({*release, {&feature}});
    } else {
      found->second.push_back(&feature);
    }
  }
  std::stable_sort(by_release.begin(), by_release.end(),
                   [](const auto& a, const auto& b) { return version_cmp(a.first, b.first) < 0; });
  Rows releases;
  for (auto group = by_release.rbegin(); group != by_release.rend(); ++group) {
    std::vector<std::string> names;
    names.reserve(group->second.size());
    for (const Feature* feature : group->second) names.push_back(escape(feature->name));
    std::ranges::sort(names);
    std::string preview;
    for (std::size_t index = 0; index < std::min<std::size_t>(6, names.size()); ++index) {
      if (index > 0) preview += ", ";
      preview += names[index];
    }
    const std::size_t more = names.size() > 6 ? names.size() - 6 : 0;
    if (more > 0) preview += std::format(", +{} more", more);
    releases.push_back({group->first, std::to_string(group->second.size()), preview});
  }
  out += table({"release", "features", "first in that release"}, releases);

  if (id == "gcc") {
    out += kGccNotes;
  } else if (id == "clang") {
    out += kClangNotes;
  } else if (id == "msvc") {
    out += kMsvcNotes;
  }
  out += std::format(
      "\n## Look one up\n\n```sh\ncpp-anything matrix features --toolchain {} --version {} --std "
      "c++23\ncpp-anything matrix explain std::expected\n```\n",
      id, latest);
  if (id == "msvc") {
    out += "\n## MSVC version to Visual Studio\n\n";
    Rows titles;
    for (const auto& [version, release_title] : matrix.msvc_titles) {
      titles.push_back({version, escape(release_title)});
    }
    std::ranges::stable_sort(titles, [](const auto& a, const auto& b) {
      return version_cmp(a[0], b[0]) < 0;
    });
    std::ranges::reverse(titles);
    out += table({"MSVC", "ships with"}, titles);
  }
  return out;
}

std::string llvm_doc(const Matrix& matrix) {
  std::string out = header(
      matrix, "LLVM, Clang and libc++",
      "LLVM releases are the unit that ships a Clang, a libc++ and the tools around them "
      "(clang-tidy, clang-format, lld, lldb, sanitizers). Clang's version number is the LLVM "
      "version; libc++ is the **clang** column of the matrix.");
  out += "## What each LLVM release brings to C++20/23\n\n";
  Rows rows;
  std::vector<std::string> releases;
  for (const Feature& feature : matrix.features) {
    const auto release = feature.first_release("clang");
    if (!release.has_value()) continue;
    if (std::ranges::find(releases, *release) == releases.end()) releases.push_back(*release);
  }
  std::ranges::stable_sort(releases,
                           [](const auto& a, const auto& b) { return version_cmp(a, b) < 0; });
  for (auto release = releases.rbegin(); release != releases.rend(); ++release) {
    std::vector<std::string> row = {"[" + *release + "](https://releases.llvm.org/" + *release +
                                    ".0.0/)"};
    for (const std::string_view standard : {"c++17", "c++20", "c++23"}) {
      if (!has_standard(matrix, standard)) continue;
      const auto [supported, partial, missing] =
          matrix.supported_counts("clang", *release, standard);
      row.push_back(std::format("{} (+{} partial, {} missing)", supported, partial, missing));
    }
    rows.push_back(std::move(row));
  }
  out += table({"LLVM", "C++17 core", "C++20 core", "C++23 core"}, rows);
  out +=
      "\nA row counts core-language features only, because that is what Clang implements; the "
      "library column is shown in [clang.md](clang.md).\n";
  out += kClangNotes;
  out += "\n## Tooling follows the release\n\n";
  out +=
      "- `clang-tidy`, `clang-format`, `clangd`, `lld`, `lldb` and the sanitizers are released "
      "with the same version as the compiler. Pin them together: `clang-format` reformatting code "
      "for a different version than the one that compiles it is a common source of noise.\n";
  out +=
      "- For a port, `clang-tidy` with `modernize-*` and `cppcoreguidelines-*` is the cheapest "
      "check that generated code is still C++20/23 rather than C++11 with extra steps.\n";
  out +=
      "- Sanitizers (`-fsanitize=address,undefined`) find the integer and lifetime bugs a Python "
      "port introduces; run the driver under them before `gate` on a real project.\n";
  return out;
}

std::string standard_doc(const Matrix& matrix, std::string_view standard) {
  const std::vector<const Feature*> features = matrix.features_in(standard);
  std::size_t core = 0;
  std::size_t library = 0;
  for (const Feature* feature : features) {
    (feature->kind == Kind::Core ? core : library) += 1;
  }
  std::string out = header(
      matrix, std::format("{} feature support", standard),
      std::format("Every {} feature in the matrix ({} core, {} library), with the first GCC, "
                  "Clang/libc++ and MSVC/MSVC STL release that implements it completely. Releases "
                  "in parentheses are partial; `—` means no release recorded.",
                  standard, core, library));
  Rows rows;
  for (const Feature* feature : features) {
    if (feature->kind != Kind::Core) continue;
    rows.push_back({escape(feature->name), "`" + feature->macro_id + "`", feature->paper,
                    cell(feature->toolchain("gcc")), cell(feature->toolchain("clang")),
                    cell(feature->toolchain("msvc"))});
  }
  out += std::format("## Core language ({})\n\n", core);
  out += table({"feature", "macro", "paper", "GCC", "Clang", "MSVC"}, rows);
  Rows library_rows;
  for (const Feature* feature : features) {
    if (feature->kind != Kind::Library) continue;
    library_rows.push_back({escape(feature->name), "`" + feature->macro_id + "`",
                            cell(feature->toolchain("gcc")), cell(feature->toolchain("clang")),
                            cell(feature->toolchain("msvc"))});
  }
  out += std::format("\n## Library ({})\n\n", library);
  out += table({"feature", "macro", "libstdc++", "libc++", "MSVC STL"}, library_rows);
  out +=
      "\nFor cpp-anything's own code generation, the facilities it emits are gated by "
      "`include/cppan/profile.hpp`; see [selecting-a-toolchain.md](selecting-a-toolchain.md).\n";
  return out;
}

std::string full_matrix_doc(const Matrix& matrix) {
  std::string out = header(
      matrix, "Full compiler support matrix",
      "One row per feature the matrix records, across every standard it tracks. Meant for search, "
      "not for reading end to end.");
  Rows rows;
  std::vector<const Feature*> features;
  features.reserve(matrix.features.size());
  for (const Feature& feature : matrix.features) features.push_back(&feature);
  std::ranges::sort(features, [](const Feature* a, const Feature* b) {
    if (a->std_number() != b->std_number()) return a->std_number() < b->std_number();
    if (kind_label(a->kind) != kind_label(b->kind)) return kind_label(a->kind) < kind_label(b->kind);
    return a->name < b->name;
  });
  for (const Feature* feature : features) {
    rows.push_back({feature->standard, std::string(kind_label(feature->kind)),
                    escape(feature->name), cell(feature->toolchain("gcc")),
                    cell(feature->toolchain("clang")), cell(feature->toolchain("msvc")),
                    "`" + feature->macro_id + "`"});
  }
  out += table({"std", "kind", "feature", "GCC", "Clang/libc++", "MSVC", "macro"}, rows);
  return out;
}

std::string selection_doc(const Matrix& matrix) {
  std::string out = header(
      matrix, "Selecting a toolchain",
      "cpp-anything's default target is C++23 on GCC 13: the oldest release in the matrix with "
      "`-std=c++23`, complete C++20 core support and a libstdc++ that has `std::expected`. This "
      "page explains the default and lists the alternatives.");
  out += "## The default, and why\n\n";
  out += "`bridge` writes `--toolchain gcc --version 13 --std c++23` unless told otherwise:\n\n";
  out +=
      "- C++23 is the policy cpp-anything's generated code is written for: `[[nodiscard]]`, "
      "`std::string_view`, `std::span`, ranges and `std::expected` everywhere.\n";
  out +=
      "- The wire format needs a value-or-error type. On C++23 targets that is `std::expected`; on "
      "C++20 targets the generated header defines `cppan::Result<T>` with the same interface, so "
      "the same port source compiles for either standard.\n";
  out +=
      "- GCC 13 is the default because it is the oldest release with `-std=c++23`, complete C++20 "
      "core support and a libstdc++ that has `std::expected`; a newer GCC closes the C++23 gaps "
      "listed in [compilers/gcc.md](compilers/gcc.md).\n";

  out += "\n## Minimum release per target, from the matrix\n\n";
  Rows rows;
  for (const std::string_view standard : {"c++20", "c++23"}) {
    for (const auto& [toolchain, name] :
         {std::pair<std::string_view, std::string_view>{"gcc", "GCC"},
          {"clang", "Clang/libc++"}, {"msvc", "MSVC/MSVC STL"}}) {
      rows.push_back({std::string(standard), std::string(name),
                      matrix.first_complete_core(toolchain, standard).value_or("—"),
                      matrix.first_complete_library(toolchain, standard).value_or("—")});
    }
  }
  out += table({"standard", "toolchain", "core complete", "library complete"}, rows);

  out += "\n## Choosing\n\n";
  out += table(
      {"situation", "pick"},
      {
          {"new code, no constraint",
           "GCC 15+ or Clang 20+ with libc++, `c++23`"},
          {"Linux distribution default (GCC 13/14)",
           "GCC 13/14, `c++23`; check `<mdspan>`/`<flat_map>` before using them"},
          {"Apple platform",
           "Apple Clang with libc++, `c++20` unless the deployment target ships a newer libc++"},
          {"Windows, MSVC toolset", "VS 2022 17.14+ (19.44), `/std:c++latest`, `/Zc:__cplusplus`"},
          {"must not upgrade the compiler",
           "run `cpp-anything matrix features --toolchain … --version … --std …` and port only "
           "what it supports; `gate` refuses the rest"},
      });

  out += "\n## What the generated profile turns off\n\n";
  out +=
      "`include/cppan/profile.hpp` maps each facility cpp-anything emits to the feature-test "
      "macro the matrix knows. A port may use `CPPAN_HAS_MDSPAN`, `CPPAN_HAS_PRINT`, "
      "`CPPAN_HAS_FLAT_MAP`, `CPPAN_HAS_LIB_MODULES` and friends only when the macro is 1. "
      "`CPPAN_HAS_EXPECTED` selects `std::expected` over the `cppan::Result` fallback — the port "
      "does not have to care which.\n";
  out +=
      "\n```sh\ncpp-anything matrix profile --toolchain gcc --version 13 --std c++23 > "
      "profile.hpp\n```\n";
  out += "\n## The matrix is data, not a promise\n\n";
  out +=
      "Every guide here is generated from cppreference's tables, with the page revision and fetch "
      "time in [README.md](README.md). If a cell disagrees with reality on your machine, the "
      "compiler wins: fix the data (`scripts/sync_matrix.py`) rather than the guide.\n";
  return out;
}

