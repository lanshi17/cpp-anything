//! The C++ front door: a binary that owns the CLI's entry point, answers what has
//! been wired to a port, and falls back to the original for everything else.
//!
//! Fallback is explicit and auditable: every case says whether it ran the port or
//! the original, and `app lift` refuses while any case still falls back.

use std::path::{Path, PathBuf};

use crate::appcase::Config;
use crate::json::Json;
use crate::util;

const MAIN_CPP: &str = r#"// Generated by cpp-anything app front-door. The entry point belongs to C++ now:
// routed commands answer natively, everything else runs the original.
#include <cstdlib>
#include <cstring>

int cppan_route(int argc, char** argv, int* code);
int cppan_fallback(int argc, char** argv, const char* unit);

int main(int argc, char** argv) {
  if (const char* force = std::getenv("CPPAN_FORCE_FALLBACK");
      force != nullptr && std::strcmp(force, "1") == 0) {
    return cppan_fallback(argc, argv, "forced");
  }
  int code = 0;
  if (cppan_route(argc, argv, &code)) return code;
  return cppan_fallback(argc, argv, nullptr);
}
"#;

const ROUTING_CPP: &str = r#"// Generated by cpp-anything app front-door; `app wire` adds entries.
#include <cstdlib>
#include <cstring>
#include <string>

int cppan_route(int argc, char** argv, int* code) {
  if (argc < 2) return 0;
  ROUTES
  return 0;
}
"#;

const GLUE_HPP: &str = r#"// The contract between the front door and a ported unit.
//
// Each `src/glue_<unit>.cpp` defines `bool handle_<unit>(int argc, char** argv,
// int* code)`: answer the command natively (fill `*code`, return true), or return
// false and the front door runs the original. There is no shared symbol here on
// purpose: handlers are per unit, declared where `routing.cpp` uses them.
#pragma once
"#;

const GLUE_CPP: &str = r#"// Generated by cpp-anything app wire for the `{{COMMAND}}` command.
//
// Fill it in after the unit passes `gate`: check argv[1] and the flags you support,
// call the port, print what the original prints, set `*code`, return true. Anything
// you cannot answer yet: return false and the front door runs the original, so the
// build stays shippable while you wire the rest.
#include "cppan/glue.hpp"
#include "{{NS}}/port.hpp"

#include <cstdio>
#include <cstring>
#include <string_view>

bool CPPAN_HANDLER(int argc, char** argv, int* code) {
  if (argc < 2 || std::strcmp(argv[1], "{{COMMAND}}") != 0) return false;
  (void)argv;
  (void)code;
  // Example once the unit is ported (the signature is in include/{{NS}}/port.hpp):
  //   auto result = {{NS}}::some_function(std::string_view{argv[2]});
  //   if (!result) { std::fprintf(stderr, "%s
", result.error().message.c_str()); *code = 1; return true; }
  //   std::printf("%s
", result->c_str());
  //   *code = 0;
  //   return true;
  return false;
}
"#;

const CMAKE: &str = r#"cmake_minimum_required(VERSION 3.28)
project(cppan_app LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 23)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)
if(NOT CMAKE_BUILD_TYPE AND NOT CMAKE_CONFIGURATION_TYPES)
  set(CMAKE_BUILD_TYPE Release CACHE STRING "Build type" FORCE)
endif()

file(GLOB GLUE_SOURCES CONFIGURE_DEPENDS src/glue_*.cpp)
add_executable(cppan_app src/main.cpp src/fallback.cpp src/routing.cpp ${GLUE_SOURCES})
target_include_directories(cppan_app PRIVATE include)
set(CPPAN_UNIT_LIBS "")
if(EXISTS ${CMAKE_CURRENT_SOURCE_DIR}/units.cmake)
  include(${CMAKE_CURRENT_SOURCE_DIR}/units.cmake)
endif()
if(CPPAN_UNIT_LIBS)
  target_link_libraries(cppan_app PRIVATE ${CPPAN_UNIT_LIBS})
endif()
if(MSVC)
  target_compile_options(cppan_app PRIVATE /W4 /permissive- /Zc:__cplusplus /utf-8)
else()
  target_compile_options(cppan_app PRIVATE -Wall -Wextra -Wpedantic)
endif()
"#;

pub fn write(app_dir: &Path, config: &Config) -> Result<usize, String> {
    let mut written = 0;
    util::write(&app_dir.join("CMakeLists.txt"), CMAKE)?;
    written += 1;
    util::write(&app_dir.join("src/main.cpp"), MAIN_CPP)?;
    written += 1;
    let repo = app_dir
        .parent()
        .and_then(Path::parent)
        .unwrap_or(Path::new("."));
    util::write(
        &app_dir.join("src/fallback.cpp"),
        &render_fallback(config, repo),
    )?;
    written += 1;
    util::write(&app_dir.join("include/cppan/glue.hpp"), GLUE_HPP)?;
    written += 1;
    let routes = load_routes(app_dir)?;
    util::write(&app_dir.join("src/routing.cpp"), &render_routing(&routes))?;
    written += 1;
    util::write(&app_dir.join("README.md"), &render_readme(config, &routes))?;
    written += 1;
    Ok(written)
}

fn routes_path(app_dir: &Path) -> PathBuf {
    app_dir.join("routes.json")
}

#[derive(Clone, Debug)]
pub struct Route {
    pub command: String,
    pub unit: String,
    pub project: String,
}

fn load_routes(app_dir: &Path) -> Result<Vec<Route>, String> {
    let path = routes_path(app_dir);
    if !path.exists() {
        return Ok(Vec::new());
    }
    let doc = Json::parse(&util::read(&path)?)?;
    let mut out = Vec::new();
    for route in doc
        .get("routes")
        .and_then(Json::as_array)
        .unwrap_or_default()
    {
        out.push(Route {
            command: route
                .get("command")
                .and_then(Json::as_str)
                .unwrap_or("")
                .to_string(),
            unit: route
                .get("unit")
                .and_then(Json::as_str)
                .unwrap_or("")
                .to_string(),
            project: route
                .get("project")
                .and_then(Json::as_str)
                .unwrap_or("")
                .to_string(),
        });
    }
    Ok(out)
}

fn save_routes(app_dir: &Path, routes: &[Route]) -> Result<(), String> {
    let doc = Json::obj([(
        "routes",
        Json::Array(
            routes
                .iter()
                .map(|route| {
                    Json::obj([
                        ("command", Json::str(route.command.clone())),
                        ("unit", Json::str(route.unit.clone())),
                        ("project", Json::str(route.project.clone())),
                    ])
                })
                .collect(),
        ),
    )]);
    util::write(&routes_path(app_dir), &doc.to_string_pretty())?;
    // One CMake fragment wires every unit the front door links.
    let mut cmake =
        String::from("# Generated by cpp-anything app wire: the ports this front door links.\n");
    let mut seen = std::collections::BTreeSet::new();
    for route in routes {
        if route.project.is_empty() || !seen.insert(route.unit.clone()) {
            continue;
        }
        let target = format!(
            "cppan_port_{}",
            crate::util::sanitize_identifier(&route.unit)
        );
        cmake.push_str(&format!(
            "add_subdirectory({project} unit_{target} EXCLUDE_FROM_ALL)\nlist(APPEND CPPAN_UNIT_LIBS {target})\n",
            project = route.project,
            target = target
        ));
    }
    util::write(&app_dir.join("units.cmake"), &cmake)
}

pub fn route_count(app_dir: &Path) -> usize {
    load_routes(app_dir).map(|routes| routes.len()).unwrap_or(0)
}

fn render_routing(routes: &[Route]) -> String {
    let mut body = String::new();
    for route in routes {
        let handler = format!("handle_{}", crate::util::sanitize_identifier(&route.unit));
        body.push_str(&format!(
            "bool {handler}(int argc, char** argv, int* code);\n"
        ));
    }
    body.push('\n');
    for route in routes.iter().filter(|route| route.command != "*") {
        let command = &route.command;
        let handler = format!("handle_{}", crate::util::sanitize_identifier(&route.unit));
        let switch = format!(
            "CPPAN_UNIT_{}",
            crate::util::sanitize_identifier(&route.unit).to_uppercase()
        );
        body.push_str(&format!(
            "  if (std::strcmp(argv[1], {command:?}) == 0) {{\n    \
             if (const char* value = std::getenv(\"{switch}\"); value != nullptr && \
             std::strcmp(value, \"original\") == 0) return 0;\n    \
             if ({handler}(argc, argv, code)) return 1;\n  }}\n",
            command = command,
        ));
    }
    // A `*` route runs last: the app's own commands (usage, unknown flags) still get
    // answered by the port instead of falling back.
    for route in routes.iter().filter(|route| route.command == "*") {
        let handler = format!("handle_{}", crate::util::sanitize_identifier(&route.unit));
        let switch = format!(
            "CPPAN_UNIT_{}",
            crate::util::sanitize_identifier(&route.unit).to_uppercase()
        );
        body.push_str(&format!(
            "  {{\n    if (const char* value = std::getenv(\"{switch}\"); value != nullptr && \
             std::strcmp(value, \"original\") == 0) return 0;\n    \
             if (argc < 2) {{ if ({handler}(argc, argv, code)) return 1; return 0; }}\n    \
             if ({handler}(argc, argv, code)) return 1;\n  }}\n"
        ));
    }
    ROUTING_CPP.replace("ROUTES", &body)
}

fn render_fallback(config: &Config, repo: &Path) -> String {
    let words = crate::appcase::resolve_command(repo, &config.run)
        .iter()
        .map(|word| format!("{word:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let args = config
        .args
        .iter()
        .map(|word| format!("{word:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"// Generated by cpp-anything app front-door: the original command, baked in.
#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

#if defined(_WIN32)
#include <process.h>
#define CPPAN_EXEC _execvp
#else
#include <unistd.h>
#define CPPAN_EXEC execvp
#endif

namespace {{

void log_fallback(const char* unit) {{
  const char* path = std::getenv("CPPAN_FALLBACK_LOG");
  if (path == nullptr || *path == '\0') return;
  if (FILE* file = std::fopen(path, "a")) {{
    std::fprintf(file, "%s\n", unit != nullptr ? unit : "original");
    std::fclose(file);
  }}
}}

}}  // namespace

// Replaces this process with the original, so a fallback is indistinguishable from
// running it directly: same stdout, stderr, exit code and signals.
int cppan_fallback(int argc, char** argv, const char* unit) {{
  log_fallback(unit);
  std::vector<std::string> words = {{{words}}};
  std::vector<std::string> server = {{{args}}};
  words.insert(words.end(), server.begin(), server.end());
  for (int index = 1; index < argc; ++index) words.emplace_back(argv[index]);
  std::vector<char*> exec;
  exec.reserve(words.size() + 1);
  for (auto& word : words) exec.push_back(word.data());
  exec.push_back(nullptr);
  CPPAN_EXEC(exec[0], exec.data());
  std::perror("cppan front door: cannot run the original");
  return 127;
}}
"#,
        words = words
    )
}

fn render_readme(config: &Config, routes: &[Route]) -> String {
    let mut out = format!(
        "# {} — C++ front door\n\n\
         Generated by `cpp-anything app front-door`. The binary owns the CLI's entry point:\n\
         a command that has been wired answers natively, everything else execs the original\n\
         ({}) with the same arguments, so stdout, stderr, exit code and signals are identical.\n\n\
         - routes: {}\n\
         - kill switch: `CPPAN_UNIT_<NAME>=original` forces a unit back to the original\n\
         - force everything back: `CPPAN_FORCE_FALLBACK=1`\n\
         - fallback log: `CPPAN_FALLBACK_LOG=<path>` gets one line per fallback\n\n\
         `cpp-anything app replay . --build <this binary>` compares it case by case;\n\
         `cpp-anything app lift .` refuses while any case still falls back.\n",
        config.name,
        config.run.join(" "),
        if routes.is_empty() {
            "none yet".to_string()
        } else {
            routes
                .iter()
                .map(|route| format!("`{}` → {}", route.command, route.unit))
                .collect::<Vec<_>>()
                .join(", ")
        }
    );
    out.push_str(
        "\n```sh\ncmake -S . -B build && cmake --build build -j\n./build/cppan_app --help\n```\n",
    );
    out
}

pub fn wire(
    app_dir: &Path,
    repo: &Path,
    unit: &str,
    command: &str,
    project: Option<&Path>,
) -> Result<PathBuf, String> {
    let normalized = crate::util::sanitize_identifier(unit);
    let project = match project {
        Some(path) => path
            .canonicalize()
            .map_err(|error| format!("{}: {error}", path.display()))?,
        None => {
            let guess = repo.join("cpp").join(normalized.replace('_', "-"));
            if !guess.join("CMakeLists.txt").exists() {
                return Err(format!(
                    "cannot find the unit's project: looked for {}. Pass `--project <dir>` (the                      folder `bridge` wrote for {unit})",
                    guess.display()
                ));
            }
            guess
                .canonicalize()
                .map_err(|error| format!("{}: {error}", guess.display()))?
        }
    };
    if !project.join("src/port.cpp").exists() {
        return Err(format!(
            "{} is not a cpp-anything project (no src/port.cpp)",
            project.display()
        ));
    }
    let mut routes = load_routes(app_dir)?;
    routes.retain(|route| route.command != command);
    routes.push(Route {
        command: command.to_string(),
        unit: normalized.clone(),
        project: project.display().to_string(),
    });
    save_routes(app_dir, &routes)?;
    let glue = app_dir.join("src").join(format!("glue_{normalized}.cpp"));
    if !glue.exists() {
        let handler = format!("handle_{normalized}");
        util::write(
            &glue,
            &GLUE_CPP
                .replace("CPPAN_HANDLER", &handler)
                .replace("{{NS}}", &normalized)
                .replace("{{COMMAND}}", command),
        )?;
    }
    let config = Config::load(&repo.join(crate::appcase::CASES_DIR))?;
    write(app_dir, &config)?;
    Ok(glue)
}

pub fn build(app_dir: &Path) -> Result<PathBuf, String> {
    let app_dir = &app_dir
        .canonicalize()
        .map_err(|error| format!("{}: {error}", app_dir.display()))?;
    let build_dir = app_dir.join("build");
    let configure = vec![
        "-S".to_string(),
        app_dir.display().to_string(),
        "-B".to_string(),
        build_dir.display().to_string(),
        "-DCMAKE_BUILD_TYPE=Release".to_string(),
    ];
    let run = util::run("cmake", &configure, Some(app_dir));
    if !run.ok {
        return Err(format!(
            "cmake configure failed: {}\n{}",
            run.failure(),
            util::indent(&run.stderr, 2)
        ));
    }
    let make = vec![
        "--build".to_string(),
        build_dir.display().to_string(),
        "-j".to_string(),
        "4".to_string(),
    ];
    let run = util::run("cmake", &make, Some(app_dir));
    if !run.ok {
        return Err(format!(
            "the front door did not build: {}\n{}",
            run.failure(),
            util::indent(
                &run.stderr
                    .lines()
                    .rev()
                    .take(20)
                    .collect::<Vec<_>>()
                    .into_iter()
                    .rev()
                    .collect::<Vec<_>>()
                    .join("\n"),
                2
            )
        ));
    }
    let exe = build_dir.join(if cfg!(windows) {
        "cppan_app.exe"
    } else {
        "cppan_app"
    });
    if !exe.exists() {
        return Err(format!("build succeeded but {} is missing", exe.display()));
    }
    Ok(exe)
}
