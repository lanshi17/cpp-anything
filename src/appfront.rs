pub fn build_library(app_dir: &Path) -> Result<PathBuf, String> {
    let build_dir = build_tree(app_dir)?;
    let library = build_dir.join(if cfg!(windows) {
        "cppan_api.lib"
    } else {
        "libcppan_api.a"
    });
    if !library.exists() {
        return Err(format!(
            "build succeeded but {} is missing",
            library.display()
        ));
    }
    Ok(library)
}

fn build_tree(app_dir: &Path) -> Result<PathBuf, String> {
    let app_dir = &app_dir
        .canonicalize()
        .map_err(|error| format!("{}: {error}", app_dir.display()))?;
    let build_dir = app_dir.join("build");
    let configure = vec![
        "-S".to_string(),
        app_dir.display().to_string(),
        "-B".to_string(),
        build_dir.display().to_string(),
        "-DCMAKE_BUILD_TYPE=Release".to_string(),
    ];
    let run = util::run("cmake", &configure, Some(app_dir));
    if !run.ok {
        return Err(format!(
            "cmake configure failed: {}\n{}",
            run.failure(),
            util::indent(&run.stderr, 2)
        ));
    }
    let make = vec![
        "--build".to_string(),
        build_dir.display().to_string(),
        "-j".to_string(),
        "4".to_string(),
    ];
    let run = util::run("cmake", &make, Some(app_dir));
    if !run.ok {
        return Err(format!(
            "the front door did not build: {}\n{}",
            run.failure(),
            util::indent(
                &run.stderr
                    .lines()
                    .rev()
                    .take(20)
                    .collect::<Vec<_>>()
                    .into_iter()
                    .rev()
                    .collect::<Vec<_>>()
                    .join("\n"),
                2
            )
        ));
    }
    Ok(build_dir)
}

pub fn build(app_dir: &Path) -> Result<PathBuf, String> {
    let build_dir = build_tree(app_dir)?;
    let exe = build_dir.join(if cfg!(windows) {
        "cppan_app.exe"
    } else {
        "cppan_app"
    });
    if !exe.exists() {
        return Err(format!("build succeeded but {} is missing", exe.display()));
    }
    Ok(exe)
}
