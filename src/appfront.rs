/// `app wire <repo> <unit> --route "GET /path"`: registers native HTTP routes and
/// writes the unit's handler stub. Requests the handler declines still proxy.
pub fn wire_http(
    app_dir: &Path,
    repo: &Path,
    unit: &str,
    texts: &[String],
    project: Option<&Path>,
) -> Result<PathBuf, String> {
    let normalized = crate::util::sanitize_identifier(unit);
    let project_dir = match project {
        Some(path) => path
            .canonicalize()
            .map_err(|error| format!("{}: {error}", path.display()))?,
        None => {
            let guess = repo.join("cpp").join(normalized.replace('_', "-"));
            if !guess.join("CMakeLists.txt").exists() {
                return Err(format!(
                    "cannot find the unit's project: looked for {}. Pass `--project <dir>` (the \
                     folder `bridge` wrote for {unit})",
                    guess.display()
                ));
            }
            guess
                .canonicalize()
                .map_err(|error| format!("{}: {error}", guess.display()))?
        }
    };
    let loaded = crate::project::Project::load(&project_dir)?;
    if loaded.modules {
        return Err(format!(
            "{} is a C++20 module unit, and the HTTP front door includes unit headers: \
             regenerate it with `cpp-anything bridge <repo> <unit> --modules off`",
            project_dir.display()
        ));
    }
    let ns = crate::codegen::namespace_of(&loaded);
    let mut routes = load_routes(app_dir)?;
    for text in texts {
        let (method, path) = Route::parse_http(text)?;
        for existing in &routes {
            if existing.unit == normalized {
                continue;
            }
            let same_path = existing.path.as_deref() == Some(path.as_str());
            let same_method =
                existing.method == method || existing.method.is_none() || method.is_none();
            if same_path && same_method {
                return Err(format!(
                    "{} already answers {} ({})",
                    existing.unit,
                    path,
                    existing.method.as_deref().unwrap_or("any method")
                ));
            }
        }
        routes.retain(|route| {
            !(route.unit == normalized
                && route.path.as_deref() == Some(path.as_str())
                && route.method == method)
        });
        routes.push(Route {
            command: String::new(),
            method,
            path: Some(path),
            unit: normalized.clone(),
            project: project_dir.display().to_string(),
        });
    }
    save_routes(app_dir, &routes)?;
    let handler = app_dir.join("src").join(format!("http_{normalized}.cpp"));
    if !handler.exists() {
        util::write(
            &handler,
            &HTTP_GLUE_CPP
                .replace("{{UNIT}}", &normalized)
                .replace("{{NS}}", &ns)
                .replace("{{HANDLER}}", &format!("cppan_http_{normalized}")),
        )?;
    }
    let config = Config::load(&repo.join(crate::appcase::CASES_DIR))?;
    write(app_dir, &config)?;
    Ok(handler)
}

pub fn wire(
    app_dir: &Path,
    repo: &Path,
    unit: &str,
    command: &str,
    project: Option<&Path>,
) -> Result<PathBuf, String> {
    let normalized = crate::util::sanitize_identifier(unit);
    let project = match project {
        Some(path) => path
            .canonicalize()
            .map_err(|error| format!("{}: {error}", path.display()))?,
        None => {
            let guess = repo.join("cpp").join(normalized.replace('_', "-"));
            if !guess.join("CMakeLists.txt").exists() {
                return Err(format!(
                    "cannot find the unit's project: looked for {}. Pass `--project <dir>` (the                      folder `bridge` wrote for {unit})",
                    guess.display()
                ));
            }
            guess
                .canonicalize()
                .map_err(|error| format!("{}: {error}", guess.display()))?
        }
    };
    if !project.join("src/port.cpp").exists() {
        return Err(format!(
            "{} is not a cpp-anything project (no src/port.cpp)",
            project.display()
        ));
    }
    let mut routes = load_routes(app_dir)?;
    routes.retain(|route| route.command != command);
    routes.push(Route {
        command: command.to_string(),
        method: None,
        path: None,
        unit: normalized.clone(),
        project: project.display().to_string(),
    });
    save_routes(app_dir, &routes)?;
    let glue = app_dir.join("src").join(format!("glue_{normalized}.cpp"));
    if !glue.exists() {
        let handler = format!("handle_{normalized}");
        util::write(
            &glue,
            &GLUE_CPP
                .replace("CPPAN_HANDLER", &handler)
                .replace("{{NS}}", &normalized)
                .replace("{{COMMAND}}", command),
        )?;
    }
    let config = Config::load(&repo.join(crate::appcase::CASES_DIR))?;
    write(app_dir, &config)?;
    Ok(glue)
}

/// `app front-door --library`: a C++ library that re-exports every bridged unit's
/// port, with no entry point and no fallback. Consumers include `cppan/api.hpp` and
/// call `cppan_api::<unit>::function(...)`.
pub fn write_library(repo: &Path, app_dir: &Path) -> Result<usize, String> {
    let cpp_dir = repo.join("cpp");
    let mut units: Vec<(crate::project::Project, String)> = Vec::new();
    let entries =
        std::fs::read_dir(&cpp_dir).map_err(|error| format!("{}: {error}", cpp_dir.display()))?;
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_dir() || path == app_dir {
            continue;
        }
        let Ok(project) = crate::project::Project::load(&path) else {
            continue;
        };
        if project.modules {
            return Err(format!(
                "{} is a C++20 module unit, and the library front door includes unit \
                 headers: regenerate it with `cpp-anything bridge <repo> <unit> --modules off`",
                path.display()
            ));
        }
        if !path.join("CMakeLists.txt").exists() {
            continue;
        }
        let ns = crate::codegen::namespace_of(&project);
        units.push((project, ns));
    }
    if units.is_empty() {
        return Err(format!(
            "no bridged units under {}: run `cpp-anything bridge` for the units the library \
             re-exports, then `app wire <unit>` or `app front-door --library`",
            cpp_dir.display()
        ));
    }
    units.sort_by(|a, b| a.1.cmp(&b.1));
    let mut cmake = String::from(
        "# Generated by cpp-anything app front-door --library: the ports this library re-exports.\n",
    );
    for (project, _) in &units {
        let target = format!(
            "cppan_port_{}",
            crate::util::sanitize_identifier(&project.unit)
        );
        cmake.push_str(&format!(
            "add_subdirectory({project} unit_{target} EXCLUDE_FROM_ALL)\nlist(APPEND CPPAN_UNIT_LIBS {target})\n",
            project = project.dir.display(),
            target = target
        ));
    }
    let mut written = 0;
    util::write(&app_dir.join("units.cmake"), &cmake)?;
    written += 1;
    let target = repo
        .file_name()
        .map(|name| crate::util::sanitize_identifier(&name.to_string_lossy()))
        .unwrap_or_else(|| "app".to_string());
    util::write(
        &app_dir.join("CMakeLists.txt"),
        &LIBRARY_CMAKE.replace("{{TARGET}}", &target),
    )?;
    written += 1;
    let mut header = String::from(
        "// Generated by cpp-anything app front-door --library.\n//\n// Each unit's port is re-exported under `cppan_api`; link the `cppan_api`\n// target and include this header. C++20/23, warnings on.\n#pragma once\n\n#include <cppan/wire.hpp>\n",
    );
    for (_, ns) in &units {
        header.push_str(&format!("#include <{ns}/port.hpp>\n"));
    }
    header.push_str(
        "\nextern \"C\" const char* cppan_api_units();\n\nnamespace cppan_api {\n\n/// The units this library re-exports, comma separated.\ninline const char* units() { return cppan_api_units(); }\n",
    );
    for (project, ns) in &units {
        header.push_str(&format!(
            "namespace {ns} = ::{ns};  // {}\n",
            project.module
        ));
    }
    header.push_str("\n}  // namespace cppan_api\n");
    util::write(&app_dir.join("include/cppan/api.hpp"), &header)?;
    written += 1;
    let names = units
        .iter()
        .map(|(_, ns)| ns.clone())
        .collect::<Vec<_>>()
        .join(",");
    util::write(
        &app_dir.join("src/api.cpp"),
        &format!(
            "// Generated by cpp-anything app front-door --library.\n#include \"cppan/api.hpp\"\n\nextern \"C\" {{\n\nconst char* cppan_api_units() {{ return \"{names}\"; }}\n\n}}  // extern \"C\"\n"
        ),
    )?;
    written += 1;
    util::write(
        &app_dir.join("README.md"),
        &format!(
            "# {} — C++ library front door\n\nGenerated by `cpp-anything app front-door --library`: every bridged unit's\nport is re-exported under `cppan_api`, with no entry point and no fallback.\n\n## Units\n\n{}\n\n## Use\n\n```cpp\n#include <cppan/api.hpp>\n\nint main() {{\n  // auto words = cppan_api::UNIT::word_count(std::string_view{{\"a b c\"}});\n}}\n```\n\n```sh\ncmake -S . -B build && cmake --build build -j\n```\n\nConsumers link the `cppan_api` target (or the static library and each unit's\n`cppan_port_*` target listed in `units.cmake`).\n",
            target,
            units
                .iter()
                .map(|(project, ns)| format!("- `cppan_api::{ns}` — {}", project.module))
                .collect::<Vec<_>>()
                .join("\n")
        ),
    )?;
    written += 1;
    Ok(written)
}

