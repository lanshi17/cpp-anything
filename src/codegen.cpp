std::string render_batch_py(const Project& project, std::string_view ns) {
  const std::string dir = (project.dir / "batch").string();
  const std::string library = (project.dir / "build" / library_file_name()).string();
  std::vector<std::pair<std::string, std::string>> entries;
  for (const Batch& batch : project.batches) {
    const std::string prefix =
        sanitize_identifier(batch.function) + "_" + sanitize_identifier(batch.param);
    entries.emplace_back(prefix, camel(sanitize_identifier(batch.function)) + "Batch");
  }
  Json::Array entries_json;
  for (const auto& [prefix, klass] : entries) {
    entries_json.push_back(
        Json::object({{"prefix", Json::string(prefix)}, {"class", Json::string(klass)}}));
  }
  std::string bodies;
  for (const auto& [prefix, klass] : entries) {
    if (!bodies.empty()) bodies += "\n\n";
    bodies += "# " + prefix +
              ": many items, one crossing. `run(*args)` answers for every item on all cores.\n"
              "class " +
              klass + "(_Batch):\n    prefix = \"" + prefix + "\"\n    name = \"" + prefix +
              "\"\n";
  }
  std::string classes;
  for (const auto& [prefix, klass] : entries) {
    (void)prefix;
    if (!classes.empty()) classes += ", ";
    classes += klass;
  }
  std::string text = embedded(std::string_view(data::batch_py, data::batch_py_size),
                              data::batch_py_size);
  text = replace_all(std::move(text), "{{MODULE}}", project.module);
  text = replace_all(std::move(text), "{{NS}}", ns);
  text = replace_all(std::move(text), "{{BATCH_DIR}}", dir);
  text = replace_all(std::move(text), "{{PROJECT_DIR}}", project.dir.string());
  text = replace_all(std::move(text), "{{LIBRARY}}", library);
  text = replace_all(std::move(text), "{{BATCHES}}", dump(Json::array(std::move(entries_json))));
  text = replace_all(std::move(text), "{{CLASSES}}", classes);
  text = replace_all(std::move(text), "{{CLASS_BODIES}}", bodies);
  return text;
}

