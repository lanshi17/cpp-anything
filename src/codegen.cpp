void replace_char(std::string& text, char from, std::string_view to) {
  std::string out;
  out.reserve(text.size());
  for (const char ch : text) {
    if (ch == from) {
      out += to;
    } else {
      out += ch;
    }
  }
  text = std::move(out);
}

std::string rust_debug_string(std::string_view text) {
  std::string out = "\"";
  for (const char ch : text) {
    switch (ch) {
      case '"': out += "\\\""; break;
      case '\\': out += "\\\\"; break;
      case '\n': out += "\\n"; break;
      case '\r': out += "\\r"; break;
      case '\t': out += "\\t"; break;
      default: out += ch; break;
    }
  }
  out += '"';
  return out;
}

std::string camel(std::string_view text) {
  std::string out;
  std::size_t start = 0;
  while (start <= text.size()) {
    const std::size_t underscore = text.find('_', start);
    std::string_view part =
        underscore == std::string_view::npos ? text.substr(start)
                                             : text.substr(start, underscore - start);
    if (!part.empty()) {
      out += static_cast<char>(std::toupper(static_cast<unsigned char>(part.front())));
      out += part.substr(1);
    }
    if (underscore == std::string_view::npos) break;
    start = underscore + 1;
  }
  return out;
}

std::string signature_headers(const Project& project) {
  std::vector<std::string> headers = {"<cstdint>", "<map>",     "<optional>", "<span>",
                                      "<string>",  "<string_view>", "<tuple>", "<vector>"};
  for (const Function& function : project.functions) {
    for (const Param& param : function.params) param.ty.headers(headers);
    function.returns.headers(headers);
  }
  std::vector<std::string> kept;
  for (const std::string& header : headers) {
    if (header.starts_with('<')) kept.push_back(header);
  }
  std::ranges::sort(kept);
  kept.erase(std::unique(kept.begin(), kept.end()), kept.end());
  std::string out;
  for (const std::string& header : kept) out += "#include " + header + "\n";
  return out;
}

std::string render_declarations(const Project& project, std::string_view ns, bool exported) {
  std::string out = (exported ? "export namespace " : "namespace ") + std::string(ns) + " {\n\n";
  out += "using cppan::PortError;\n";
  for (const Function& function : project.functions) {
    out += '\n';
    if (!function.doc.empty()) {
      out += std::format("// {} — {}\n", function.name, function.doc);
    }
    if (function.returns.kind == Ty::Kind::Any) {
      out +=
          "// no return annotation: this returns cppan::Json; give it a real type in the port\n";
    }
    out += function.cpp_declaration() + "\n";
  }
  out += "\n}  // namespace " + std::string(ns) + "\n";
  return out;
}

std::string render_port_hpp(const Project& project, std::string_view ns) {
  std::string out = std::format(
      "// Port of {} ({}) to C++. Declarations only: write the bodies in src/port.cpp.\n",
      project.module, project.source_lang);
  out += "//\n// Generated by cpp-anything bridge; `cpp-anything refresh` regenerates the\n";
  out += "// declarations from the original's signature after you change one.\n";
  out += "#pragma once\n\n";
  out += signature_headers(project);
  out += "\n#include \"cppan/wire.hpp\"\n\n";
  out += render_declarations(project, ns, false);
  return out;
}

