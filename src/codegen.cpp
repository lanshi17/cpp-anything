std::string namespace_of(const Project& project) { return sanitize_identifier(project.unit); }

Result<std::vector<std::pair<std::string, std::string>>> project_files(const Project& project) {
  const std::string ns = namespace_of(project);
  std::vector<std::pair<std::string, std::string>> files;
  files.emplace_back("CMakeLists.txt", render_cmake(project, ns));
  files.emplace_back("include/cppan/json.hpp",
                     embedded(std::string_view(data::json_hpp, data::json_hpp_size),
                              data::json_hpp_size));
  files.emplace_back("include/cppan/wire.hpp",
                     embedded(std::string_view(data::wire_hpp, data::wire_hpp_size),
                              data::wire_hpp_size));
  files.emplace_back("include/cppan/profile.hpp",
                     render_profile(project.target.toolchain, project.target.version,
                                    project.target.standard));
  if (project.modules) {
    files.emplace_back("src/port.cppm", render_port_cppm(project, ns));
  } else {
    files.emplace_back("include/" + ns + "/port.hpp", render_port_hpp(project, ns));
  }
  files.emplace_back("src/port.cpp", render_port_cpp(project, ns));
  files.emplace_back("src/dispatch.cpp", render_dispatch(project, ns));
  files.emplace_back("src/main.cpp", render_main(project));
  files.emplace_back("src/shadow.cpp",
                     embedded(std::string_view(data::shadow_cpp, data::shadow_cpp_size),
                              data::shadow_cpp_size));
  files.emplace_back("src/batch.cpp", render_batch_cpp(project));
  files.emplace_back("batch/" + ns + "_batch.py", render_batch_py(project, ns));
  files.emplace_back("README.md", render_readme(project, ns));
  files.emplace_back(".clang-format", std::string(kClangFormat));
  files.emplace_back(".gitignore", "build/\n");
  if (const auto lang = langs::parse(project.source_lang); lang.has_value()) {
    auto shadow_files = langs::shadow_files(project, ns);
    if (!shadow_files) return std::unexpected(shadow_files.error());
    for (auto& file : *shadow_files) files.push_back(std::move(file));
    files.emplace_back("shadow/README.md", render_shadow_readme(project, ns, *lang));
  } else {
    files.emplace_back("shadow/" + ns + "_shadow.py", render_shadow_py(project, ns));
  }
  files.emplace_back(".cppan/inventory.json", dump(unit_inventory(project), true));
  return files;
}

Result<std::vector<std::string>> write_project(Project& project, bool force) {
  auto files = project_files(project);
  if (!files) return std::unexpected(files.error());
  std::vector<std::string> written;
  for (const auto& [relative, contents] : *files) {
    const std::filesystem::path path = project.dir / relative;
    std::error_code error;
    if (std::filesystem::exists(path, error) && !force) continue;
    auto result = write_file(path, contents);
    if (!result) return std::unexpected(path.string() + ": " + result.error());
    written.push_back(relative);
  }
  auto saved = project.save();
  if (!saved) return std::unexpected(saved.error());
  if (std::ranges::find(written, "src/port.cpp") == written.end()) {
    return std::unexpected(project.dir.string() +
                           " already has a port; pass --force to regenerate the generated files");
  }
  return written;
}

Result<std::vector<std::string>> refresh(const Project& project) {
  auto files = project_files(project);
  if (!files) return std::unexpected(files.error());
  std::vector<std::string> written;
  for (const auto& [relative, contents] : *files) {
    if (relative == "src/port.cpp") continue;
    const std::filesystem::path path = project.dir / relative;
    auto result = write_file(path, contents);
    if (!result) return std::unexpected(path.string() + ": " + result.error());
    written.push_back(relative);
  }
  auto saved = project.save();
  if (!saved) return std::unexpected(saved.error());
  return written;
}

