std::string render_readme(const Project& project, std::string_view ns) {
  const Matrix& matrix = Matrix::get();
  const Target& target = project.target;
  std::string out = std::format("# {} → C++\n\n", project.module);
  out += std::format(
      "A port of `{}` ({}), one function at a time, checked against recorded behaviour.\n\n",
      project.module, project.source_lang);
  out += std::format(
      "- source: `{}` ({} lines)\n- target: {} {} with `-std={}`\n- generated by cpp-anything {} "
      "at {}\n\n",
      project.source_file.string(), project.lines, matrix.toolchain_label(target.toolchain),
      target.version, target.standard, CPPAN_VERSION, project.created_at);
  out += "## Functions\n\n| function | Python signature | C++ signature |\n| --- | --- | --- |\n";
  for (const Function& function : project.functions) {
    std::string python = function.signature_line();
    std::string cpp = function.plain_signature();
    replace_char(python, '|', "\\|");
    replace_char(cpp, '|', "\\|");
    out += std::format("| `{}` | `{}` | `{}` |\n", function.name, python, cpp);
  }
  if (!project.skipped.empty()) {
    out += "\nSkipped by the analyzer (not ported as plain functions):\n\n";
    for (const auto& [name, reason] : project.skipped) {
      out += std::format("- `{}`: {}\n", name, reason);
    }
  }
  if (!project.imports.empty()) {
    out += "\n## What the original imports\n\n";
    out += "Each one either has a standard-library counterpart or has to be replaced by hand; "
           "the analyzer does not guess a mapping.\n\n";
    for (const std::string& name : project.imports) out += "- `" + name + "`\n";
  }
  if (project.source_lang == "cpp") {
    out += "\n## Modernization is the job\n\n";
    out +=
        "This unit is C-style C++: the port must preserve behaviour *and* be modern C++.\n"
        "`gate` fails on `NULL`, `malloc`/`free`, raw `new`/`delete`, `char*` string calls,\n"
        "`printf`, C-style casts and `typedef struct` left in `src/port.cpp`, unless a line (or\n"
        "the comment block right above it) says `// C-STYLE: why`.\n\n";
    out +=
        "Use the facilities `include/cppan/profile.hpp` reports: `CPPAN_HAS_SPAN` for\n"
        "`std::span`, `CPPAN_HAS_RANGES` for views and algorithms, `CPPAN_HAS_FORMAT`/\n"
        "`CPPAN_HAS_PRINT` for formatting, `CPPAN_HAS_STRING_VIEW`-class facilities are C++17\n"
        "and always available here. Each mapping the analyzer printed above names the macro its\n"
        "replacement needs.\n";
  }
  if (!project.risks.empty()) {
    out += "\n## Risks the analyzer flagged\n\n";
    for (const std::string& risk : project.risks) out += "- " + risk + "\n";
  }
  if (!project.batches.empty()) {
    out += "\n## Batch API\n\n";
    out += "Many items cross once and the loop stays in C++, on all cores:\n\n```python\n";
    for (const Batch& batch : project.batches) {
      const std::string klass = camel(batch.function) + "Batch";
      out += std::format(
          "from {}_batch import {}\nwith {}(items) as batch:\n    results = batch.run(...)\n    "
          "best = batch.rank(..., min=0.5)\n",
          ns, klass, klass);
      out += std::format("# items are `{}` values; other arguments stay per call\n", batch.param);
    }
    out += "```\n";
  }
  out +=
      "\n## Build, replay, gate\n\n```sh\ncmake -S . -B build\ncmake --build build -j\n./build/"
      "cppan_driver --cases cases.jsonl --out results.jsonl\ncpp-anything diff .        # every "
      "recorded case must match\ncpp-anything gate .        # done means this passes\n```\n";
  out += "\n## Rules for the port\n\n";
  out += "- Bodies live in `src/port.cpp`; `port.hpp`, `dispatch.cpp` and `main.cpp` are "
         "generated.\n";
  out += "- Failures are values: return `cppan::unexpected(PortError{\"ValueError\", message})` "
         "— the type is the original's exception class, and the diff compares it.\n";
  out += std::format(
      "- The compiler must be one the matrix knows: `cpp-anything matrix features --toolchain {} "
      "--version {} --std {}`.\n",
      target.toolchain, target.version, target.standard);
  out += "- `include/cppan/profile.hpp` says which C++20/23 facilities this toolchain has; guard "
         "optional ones with `CPPAN_HAS_*` instead of guessing.\n";
  out += "- Text in is `std::string_view`, text out is `std::string`: Python's `str` offsets are "
         "code points, C++'s are bytes, so every offset that reaches output needs a UTF-8 aware "
         "helper.\n";
  out += "- Python `int` is unbounded and `int()`/`float()` accept more syntax than "
         "`std::from_chars`; handle those in the port, not in the driver.\n";
  out += std::format("\nNamespace: `{}`.\n", ns);
  return out;
}

std::string render_cmake(const Project& project, std::string_view ns) {
  std::string port_target;
  const std::string std_num = project.target.standard.substr(3);
  if (project.modules) {
    port_target = R"(# C++20 modules. GCC's CMake support writes the BMI under CMakeFiles/, where a
# second translation unit cannot find it, so GCC gets an explicit module compile
# first (gcm.cache in the build directory); MSVC and Clang use CMake's scanner.
if(CMAKE_CXX_COMPILER_ID STREQUAL "GNU")
  # The module is compiled by the custom command below; CMake's own scan would add a
  # module mapper that hides gcm.cache from every importing translation unit.
  set(CMAKE_CXX_SCAN_FOR_MODULES OFF)
  set(CPPAN_MODULE_FLAGS -fmodules-ts)
  set(CPPAN_MODULE_OBJECT ${CMAKE_CURRENT_BINARY_DIR}/port_module.o)
  set(CPPAN_MODULE_DEPS ${CMAKE_CURRENT_BINARY_DIR}/gcm.cache/@NS@.gcm)
  add_custom_command(
    OUTPUT ${CPPAN_MODULE_OBJECT} ${CPPAN_MODULE_DEPS}
    COMMAND ${CMAKE_CXX_COMPILER} -std=c++@STDNUM@ ${CPPAN_MODULE_FLAGS}
            -I${CMAKE_CURRENT_SOURCE_DIR}/include
            -c ${CMAKE_CURRENT_SOURCE_DIR}/src/port.cppm -o ${CPPAN_MODULE_OBJECT}
    WORKING_DIRECTORY ${CMAKE_CURRENT_BINARY_DIR}
    DEPENDS src/port.cppm
    COMMENT "Compiling module @NS@")
  add_custom_target(cppan_module_@NS@ DEPENDS ${CPPAN_MODULE_OBJECT})
  # The .gcm is found through the working directory, so every object that mentions
  # the module must be compiled after it exists — including `import` sites.
  set_source_files_properties(
    src/port.cpp src/dispatch.cpp src/main.cpp src/shadow.cpp src/batch.cpp
    PROPERTIES OBJECT_DEPENDS "${CPPAN_MODULE_DEPS}")
  add_library(cppan_port_@NS@ STATIC src/port.cpp ${CPPAN_MODULE_OBJECT})
  target_compile_options(cppan_port_@NS@ PRIVATE ${CPPAN_MODULE_FLAGS})
else()
  set(CMAKE_CXX_SCAN_FOR_MODULES ON)
  add_library(cppan_port_@NS@ STATIC)
  target_sources(cppan_port_@NS@ PUBLIC FILE_SET CXX_MODULES FILES src/port.cppm)
  target_sources(cppan_port_@NS@ PRIVATE src/port.cpp)
endif()
# The shadow library links this statically: the port must be position independent.
set_target_properties(cppan_port_@NS@ PROPERTIES POSITION_INDEPENDENT_CODE ON)
target_include_directories(cppan_port_@NS@ PUBLIC ${CMAKE_CURRENT_SOURCE_DIR}/include)
target_compile_features(cppan_port_@NS@ PUBLIC cxx_std_@STDNUM@)
)";
  } else {
    port_target = R"(add_library(cppan_port_@NS@ STATIC src/port.cpp)
# The shadow library links this statically: the port must be position independent.
set_target_properties(cppan_port_@NS@ PROPERTIES POSITION_INDEPENDENT_CODE ON)
target_include_directories(cppan_port_@NS@ PUBLIC ${CMAKE_CURRENT_SOURCE_DIR}/include)
target_compile_features(cppan_port_@NS@ PUBLIC cxx_std_@STDNUM@)
)";
  }
  port_target = replace_all(std::move(port_target), "@NS@", ns);
  port_target = replace_all(std::move(port_target), "@STDNUM@", std_num);

  std::string text = R"(# Generated by cpp-anything bridge for @MODULE@ (target: @TOOLCHAIN@ @VERSION@, @STD@@MODULE_NOTE@).
cmake_minimum_required(VERSION 3.28)
project(@NS@ LANGUAGES CXX)

set(CMAKE_CXX_STANDARD @STDNUM@)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)
if(NOT CMAKE_BUILD_TYPE AND NOT CMAKE_CONFIGURATION_TYPES)
  set(CMAKE_BUILD_TYPE Release CACHE STRING "Build type" FORCE)
endif()

@PORT_TARGET@
if(MSVC)
  # /Zc:__cplusplus makes __cplusplus tell the truth; without it the
  # static_assert in profile.hpp cannot pass.
  target_compile_options(cppan_port_@NS@ PRIVATE /W4 /permissive- /Zc:__cplusplus /utf-8)
else()
  target_compile_options(cppan_port_@NS@ PRIVATE -Wall -Wextra -Wpedantic -Wconversion -Wshadow)
endif()

add_executable(cppan_driver src/main.cpp src/dispatch.cpp)
target_link_libraries(cppan_driver PRIVATE cppan_port_@NS@)

# The shadow library: the same port, callable from the original's runtime so both
# can run on real traffic and be compared (`cpp-anything shadow .`).
add_library(cppan_shadow_@NS@ SHARED src/shadow.cpp src/batch.cpp src/dispatch.cpp)
target_link_libraries(cppan_shadow_@NS@ PRIVATE cppan_port_@NS@)
set_target_properties(cppan_shadow_@NS@ PROPERTIES OUTPUT_NAME cppan_shadow)

if(CMAKE_CXX_COMPILER_ID STREQUAL "GNU" AND CPPAN_MODULE_FLAGS)
  # Every translation unit that imports the module needs the flag, and the module
  # must exist before any of them is compiled.
  target_compile_options(cppan_driver PRIVATE ${CPPAN_MODULE_FLAGS})
  target_compile_options(cppan_shadow_@NS@ PRIVATE ${CPPAN_MODULE_FLAGS})
  add_dependencies(cppan_driver cppan_module_@NS@)
  add_dependencies(cppan_shadow_@NS@ cppan_module_@NS@)
endif()
)";
  text = replace_all(std::move(text), "@MODULE@", project.module);
  text = replace_all(std::move(text), "@TOOLCHAIN@", project.target.toolchain);
  text = replace_all(std::move(text), "@VERSION@", project.target.version);
  text = replace_all(std::move(text), "@STD@", project.target.standard);
  text = replace_all(std::move(text), "@STDNUM@", std_num);
  text = replace_all(std::move(text), "@MODULE_NOTE@", project.modules ? ", C++20 modules" : "");
  text = replace_all(std::move(text), "@PORT_TARGET@", port_target);
  text = replace_all(std::move(text), "@NS@", ns);
  return text;
}

Json unit_inventory(const Project& project) {
  Json::Array functions;
  for (const Function& function : project.functions) functions.push_back(function.to_json());
  Json::Array risks;
  for (const std::string& risk : project.risks) risks.push_back(Json::string(risk));
  return Json::object({
      {"unit", Json::string(project.unit)},
      {"module", Json::string(project.module)},
      {"lang", Json::string(project.source_lang)},
      {"file", Json::string(project.source_file.string())},
      {"lines", Json::integer(project.lines)},
      {"functions", Json::array(std::move(functions))},
      {"risks", Json::array(std::move(risks))},
  });
}

