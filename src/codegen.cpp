std::string sub(std::string text, std::string_view marker, std::string_view value) {
  std::size_t at = 0;
  while ((at = text.find(marker, at)) != std::string::npos) {
    text.replace(at, marker.size(), value);
    at += value.size();
  }
  return text;
}

std::string replace_all(std::string text, std::string_view needle, std::string_view value) {
  return sub(std::move(text), needle, value);
}

