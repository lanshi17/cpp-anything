//! Code generation: the C++ project `bridge` writes, and the examples/tests it is
//! verified against.
//!
//! The generated code is C++23 (see `render_profile`): `std::expected` for failure,
//! `std::string_view` for text coming in, `std::span` for read-only sequences,
//! `[[nodiscard]]` on everything, `std::format` in the driver.

use crate::inventory::Function;
use crate::matrix;
use crate::project::Project;
use crate::types::Ty;
use crate::util;

const JSON_HPP: &str = include_str!("cpp_runtime/json.hpp");
const WIRE_HPP: &str = include_str!("cpp_runtime/wire.hpp");
const MAIN_CPP: &str = include_str!("cpp_runtime/main.cpp");
const SHADOW_CPP: &str = include_str!("cpp_runtime/shadow.cpp");
const SHADOW_PY: &str = include_str!("cpp_runtime/shadow_module.py.in");

pub fn namespace_of(project: &Project) -> String {
    util::sanitize_identifier(&project.unit)
}

/// Every generated file, relative to the project directory.
pub fn project_files(project: &Project) -> Vec<(String, String)> {
    let ns = namespace_of(project);
    let mut files = vec![
        ("CMakeLists.txt".to_string(), render_cmake(project, &ns)),
        ("include/cppan/json.hpp".to_string(), JSON_HPP.to_string()),
        ("include/cppan/wire.hpp".to_string(), WIRE_HPP.to_string()),
        (
            "include/cppan/profile.hpp".to_string(),
            matrix::render_profile(
                &project.target.toolchain,
                &project.target.version,
                &project.target.std,
            ),
        ),
        (
            format!("include/{ns}/port.hpp"),
            render_port_hpp(project, &ns),
        ),
        ("src/port.cpp".to_string(), render_port_cpp(project, &ns)),
        (
            "src/dispatch.cpp".to_string(),
            render_dispatch(project, &ns),
        ),
        ("src/main.cpp".to_string(), render_main(project)),
        ("src/shadow.cpp".to_string(), SHADOW_CPP.to_string()),
        (
            format!("shadow/{ns}_shadow.py"),
            render_shadow_py(project, &ns),
        ),
        ("README.md".to_string(), render_readme(project, &ns)),
        (".clang-format".to_string(), CLANG_FORMAT.to_string()),
        (".gitignore".to_string(), "build/\n".to_string()),
    ];
    files.push((
        format!("{}/inventory.json", crate::project::META_DIR),
        unit_inventory(project).to_string_pretty(),
    ));
    files
}

fn unit_inventory(project: &Project) -> crate::json::Json {
    crate::json::Json::obj([
        ("unit", crate::json::Json::str(project.unit.clone())),
        ("module", crate::json::Json::str(project.module.clone())),
        ("lang", crate::json::Json::str(project.source_lang.clone())),
        (
            "file",
            crate::json::Json::str(project.source_file.display().to_string()),
        ),
        ("lines", crate::json::Json::Int(i64::from(project.lines))),
        (
            "functions",
            crate::json::Json::Array(project.functions.iter().map(Function::to_json).collect()),
        ),
        (
            "risks",
            crate::json::Json::Array(
                project
                    .risks
                    .iter()
                    .map(|risk| crate::json::Json::str(risk.clone()))
                    .collect(),
            ),
        ),
    ])
}

/// Writes the project. Existing files are only replaced with `--force`; a port is
/// the user's work, and `bridge` must never overwrite it by accident.
pub fn write_project(project: &Project, force: bool) -> Result<Vec<String>, String> {
    let mut written = Vec::new();
    for (relative, contents) in project_files(project) {
        let path = project.dir.join(&relative);
        if path.exists() && !force {
            continue;
        }
        util::write(&path, &contents).map_err(|error| format!("{}: {error}", path.display()))?;
        written.push(relative);
    }
    project.save()?;
    if !written.iter().any(|name| name == "src/port.cpp") {
        return Err(format!(
            "{} already has a port; pass --force to regenerate the generated files",
            project.dir.display()
        ));
    }
    Ok(written)
}

/// Regenerates everything except `src/port.cpp`, which holds the user's work.
pub fn refresh(project: &Project) -> Result<Vec<String>, String> {
    let mut written = Vec::new();
    for (relative, contents) in project_files(project) {
        if relative == "src/port.cpp" {
            continue;
        }
        util::write(&project.dir.join(&relative), &contents)
            .map_err(|error| format!("{}: {error}", project.dir.join(&relative).display()))?;
        written.push(relative);
    }
    project.save()?;
    Ok(written)
}

fn render_cmake(project: &Project, ns: &str) -> String {
    format!(
        r#"# Generated by cpp-anything bridge for {module} (target: {toolchain} {version}, {std}).
cmake_minimum_required(VERSION 3.28)
project({ns} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD {std_num})
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)
if(NOT CMAKE_BUILD_TYPE AND NOT CMAKE_CONFIGURATION_TYPES)
  set(CMAKE_BUILD_TYPE Release CACHE STRING "Build type" FORCE)
endif()

add_library(cppan_port_{ns} STATIC src/port.cpp)
target_include_directories(cppan_port_{ns} PUBLIC ${{CMAKE_CURRENT_SOURCE_DIR}}/include)
target_compile_features(cppan_port_{ns} PUBLIC cxx_std_{std_num})
if(MSVC)
  # /Zc:__cplusplus makes __cplusplus tell the truth; without it the
  # static_assert in profile.hpp cannot pass.
  target_compile_options(cppan_port_{ns} PRIVATE /W4 /permissive- /Zc:__cplusplus /utf-8)
else()
  target_compile_options(cppan_port_{ns} PRIVATE -Wall -Wextra -Wpedantic -Wconversion -Wshadow)
endif()

add_executable(cppan_driver src/main.cpp src/dispatch.cpp)
target_link_libraries(cppan_driver PRIVATE cppan_port_{ns})

# The shadow library: the same port, callable from the original's runtime so both
# can run on real traffic and be compared (`cpp-anything shadow .`).
add_library(cppan_shadow_{ns} SHARED src/shadow.cpp src/dispatch.cpp)
target_link_libraries(cppan_shadow_{ns} PRIVATE cppan_port_{ns})
set_target_properties(cppan_shadow_{ns} PROPERTIES OUTPUT_NAME cppan_shadow)
"#,
        module = project.module,
        toolchain = project.target.toolchain,
        version = project.target.version,
        std = project.target.std,
        std_num = project.target.std.trim_start_matches("c++"),
        ns = ns,
    )
}

fn render_port_hpp(project: &Project, ns: &str) -> String {
    let mut headers: Vec<String> = vec![
        "<cstdint>".into(),
        "<map>".into(),
        "<optional>".into(),
        "<span>".into(),
        "<string>".into(),
        "<string_view>".into(),
        "<tuple>".into(),
        "<vector>".into(),
    ];
    for function in &project.functions {
        for param in &function.params {
            param.ty.headers(&mut headers);
        }
        function.returns.headers(&mut headers);
    }
    headers.sort();
    headers.dedup();
    let mut out = String::new();
    out.push_str(&format!(
        "// Port of {} ({}) to C++. Declarations only: write the bodies in src/port.cpp.\n",
        project.module, project.source_lang
    ));
    out.push_str(
        "//\n// Generated by cpp-anything bridge; `cpp-anything refresh` regenerates the\n",
    );
    out.push_str("// declarations from the Python signature after you change one.\n");
    out.push_str("#pragma once\n\n");
    for header in &headers {
        out.push_str(&format!("#include {header}\n"));
    }
    out.push_str("\n#include \"cppan/wire.hpp\"\n");
    out.push_str(&format!("\nnamespace {ns} {{\n\n"));
    out.push_str("using cppan::PortError;\n");
    for function in &project.functions {
        out.push('\n');
        if !function.doc.is_empty() {
            out.push_str(&format!("// {} — {}\n", function.name, function.doc));
        }
        if function.returns == Ty::Any {
            out.push_str("// no return annotation: this returns cppan::Json; give it a real type in port.hpp\n");
        }
        out.push_str(&format!("{}\n", function.cpp_declaration()));
    }
    out.push_str(&format!("\n}}  // namespace {ns}\n"));
    out
}

fn render_port_cpp(project: &Project, ns: &str) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// Port of {} ({}) to C++23.\n//\n// Every body below is a stub: `cpp-anything gate` fails while any of them still\n// returns CPPAN_STUB. Replace the bodies; keep the signatures the header declares.\n#include \"{ns}/port.hpp\"\n\n#include \"cppan/profile.hpp\"\n\nnamespace {ns} {{\n",
        project.module, project.source_lang
    ));
    for function in &project.functions {
        out.push('\n');
        if !function.doc.is_empty() {
            out.push_str(&format!("// {}: {}\n", function.name, function.doc));
        }
        for risk in &function.risks {
            out.push_str(&format!("// risk: {risk}\n"));
        }
        out.push_str(&format!("{} {{\n", function.cpp_definition()));
        for param in &function.params {
            out.push_str(&format!("  (void){};\n", param.name));
        }
        out.push_str(&format!(
            "  return cppan::unexpected(PortError{{\"CPPAN_STUB\", \"{}\"}});\n}}\n",
            format!("{} is not ported yet", function.name).replace('"', "'")
        ));
    }
    out.push_str(&format!("\n}}  // namespace {ns}\n"));
    out
}

fn render_dispatch(project: &Project, ns: &str) -> String {
    let mut out = String::new();
    out.push_str("// Generated dispatch: one lambda per ported function. Never edit by hand.\n");
    out.push_str("//\n// `cpp-anything refresh` regenerates it when a signature changes.\n");
    out.push_str(
        "#include <cstdint>\n#include <string>\n#include <string_view>\n#include <vector>\n\n",
    );
    out.push_str("#include \"cppan/wire.hpp\"\n");
    out.push_str(&format!("#include \"{ns}/port.hpp\"\n\n"));
    out.push_str(
        r#"namespace {

template <typename... Args>
[[noreturn]] void bad_arity(const char* fn, std::size_t got, std::size_t lowest,
                            std::size_t highest) {
  std::string expected = std::to_string(lowest);
  if (highest != lowest) expected += " to " + std::to_string(highest);
  throw cppan::PortError{"TypeError", std::string(fn) + "() takes " + expected +
                                            " arguments (" + std::to_string(got) + " given)"};
}

}  // namespace

void cppan_register(cppan::Registry& registry) {
"#,
    );
    for function in &project.functions {
        let params = &function.params;
        let required = params
            .iter()
            .filter(|param| required_in_port(param))
            .count();
        let total = params.len();
        out.push_str(&format!(
            "  registry.add(\"{name}\", [](const std::vector<cppan::Json>& args) -> cppan::Json {{\n",
            name = function.name
        ));
        if total == 0 {
            out.push_str(&format!(
                "    if (!args.empty()) bad_arity(\"{name}\", args.size(), 0, 0);\n",
                name = function.name
            ));
        } else if required == total {
            out.push_str(&format!(
                "    if (args.size() != {total}) bad_arity(\"{name}\", args.size(), {total}, {total});\n",
                name = function.name
            ));
        } else {
            out.push_str(&format!(
                "    if (args.size() < {required} || args.size() > {total}) bad_arity(\"{name}\", args.size(), {required}, {total});\n",
                name = function.name
            ));
        }
        for (index, param) in params.iter().enumerate() {
            let storage = param.ty.cpp_storage();
            let default = if param.has_default {
                param
                    .default
                    .as_ref()
                    .and_then(|value| param.ty.cpp_default(value))
            } else {
                None
            };
            match default {
                Some(default) if index >= required => {
                    out.push_str(&format!(
                        "    {storage} arg{index} = {default};\n    if (args.size() > {index}) arg{index} = cppan::decode<{storage}>(args.at({index}), \"{name}\", {index});\n",
                        name = function.name
                    ));
                }
                _ => {
                    out.push_str(&format!(
                        "    const auto arg{index} = cppan::decode<{storage}>(args.at({index}), \"{name}\", {index});\n",
                        name = function.name
                    ));
                }
            }
        }
        let arguments = (0..total)
            .map(|index| format!("arg{index}"))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "    return cppan::encode_result({ns}::{name}({arguments}));\n  }});\n\n",
            ns = ns,
            name = function.name
        ));
    }
    out.push_str("}\n");
    out
}

fn required_in_port(param: &crate::inventory::Param) -> bool {
    if !param.has_default {
        return true;
    }
    param
        .default
        .as_ref()
        .and_then(|value| param.ty.cpp_default(value))
        .is_none()
}

fn render_shadow_py(project: &Project, ns: &str) -> String {
    let shadow_dir = project.dir.join("shadow").display().to_string();
    let library = project.dir.join("build").join(if cfg!(windows) {
        "cppan_shadow.dll"
    } else if cfg!(target_os = "macos") {
        "libcppan_shadow.dylib"
    } else {
        "libcppan_shadow.so"
    });
    let functions = project
        .functions
        .iter()
        .map(|function| format!("{:?}", function.name))
        .collect::<Vec<_>>()
        .join(", ");
    SHADOW_PY
        .replace("{{MODULE}}", &project.module)
        .replace("{{NS}}", ns)
        .replace("{{SHADOW_DIR}}", &shadow_dir)
        .replace("{{PROJECT_DIR}}", &project.dir.display().to_string())
        .replace("{{LIBRARY}}", &library.display().to_string())
        .replace(
            "{{ORIGINAL_FILE}}",
            &project.source_file.display().to_string(),
        )
        .replace(
            "{{ORIGINAL_ROOT}}",
            &project
                .package_root
                .as_ref()
                .map(|path| format!("r{:?}", path.display().to_string()))
                .unwrap_or_else(|| "None".to_string()),
        )
        .replace(
            "{{LOG}}",
            &project
                .dir
                .join("shadow")
                .join(format!("{ns}.shadow.jsonl"))
                .display()
                .to_string(),
        )
        .replace("{{FUNCTIONS}}", &format!("[{functions}]"))
        .replace("{{TOLERANCE}}", &format!("{:?}", project.tolerance))
}

fn render_main(project: &Project) -> String {
    let header = format!(
        "// cpp-anything driver for {} ({} -> C++).\n//\n// Generated: replayed by `cpp-anything diff`, timed by `cpp-anything bench`.\n",
        project.module, project.source_lang
    );
    let mut text = String::new();
    text.push_str(&header);
    text.push_str(MAIN_CPP);
    text
}

fn render_readme(project: &Project, ns: &str) -> String {
    let matrix = matrix::Matrix::get();
    let target = &project.target;
    let mut out = String::new();
    out.push_str(&format!("# {} → C++\n\n", project.module));
    out.push_str(&format!(
        "A port of `{}` ({}), one function at a time, checked against recorded behaviour.\n\n",
        project.module, project.source_lang
    ));
    out.push_str(&format!(
        "- source: `{}` ({} lines)\n- target: {} {} with `-std={}`\n- generated by cpp-anything {} at {}\n\n",
        project.source_file.display(),
        project.lines,
        matrix.toolchain_label(&target.toolchain),
        target.version,
        target.std,
        env!("CARGO_PKG_VERSION"),
        project.created_at
    ));
    out.push_str(
        "## Functions\n\n| function | Python signature | C++ signature |\n| --- | --- | --- |\n",
    );
    for function in &project.functions {
        let python = function.signature_line().replace('|', "\\|");
        let cpp = function.plain_signature().replace('|', "\\|");
        out.push_str(&format!(
            "| `{name}` | `{python}` | `{cpp}` |\n",
            name = function.name
        ));
    }
    if !project.skipped.is_empty() {
        out.push_str("\nSkipped by the analyzer (not ported as plain functions):\n\n");
        for (name, reason) in &project.skipped {
            out.push_str(&format!("- `{name}`: {reason}\n"));
        }
    }
    if !project.imports.is_empty() {
        out.push_str("\n## What the original imports\n\n");
        out.push_str(
            "Each one either has a standard-library counterpart or has to be replaced by hand; \
             the analyzer does not guess a mapping.\n\n",
        );
        for name in &project.imports {
            out.push_str(&format!("- `{name}`\n"));
        }
    }
    if !project.risks.is_empty() {
        out.push_str("\n## Risks the analyzer flagged\n\n");
        for risk in &project.risks {
            out.push_str(&format!("- {risk}\n"));
        }
    }
    out.push_str("\n## Build, replay, gate\n\n```sh\ncmake -S . -B build\ncmake --build build -j\n./build/cppan_driver --cases cases.jsonl --out results.jsonl\ncpp-anything diff .        # every recorded case must match\ncpp-anything gate .        # done means this passes\n```\n");
    out.push_str("\n## Rules for the port\n\n");
    out.push_str("- Bodies live in `src/port.cpp`; `port.hpp`, `dispatch.cpp` and `main.cpp` are generated.\n");
    out.push_str("- Failures are values: return `cppan::unexpected(PortError{\"ValueError\", message})` — the type is the original's exception class, and the diff compares it.\n");
    out.push_str(&format!("- The compiler must be one the matrix knows: `cpp-anything matrix features --toolchain {} --version {} --std {}`.\n", target.toolchain, target.version, target.std));
    out.push_str("- `include/cppan/profile.hpp` says which C++20/23 facilities this toolchain has; guard optional ones with `CPPAN_HAS_*` instead of guessing.\n");
    out.push_str("- Text in is `std::string_view`, text out is `std::string`: Python's `str` offsets are code points, C++'s are bytes, so every offset that reaches output needs a UTF-8 aware helper.\n");
    out.push_str("- Python `int` is unbounded and `int()`/`float()` accept more syntax than `std::from_chars`; handle those in the port, not in the driver.\n");
    out.push_str(&format!("\nNamespace: `{ns}`.\n"));
    out
}

